create or replace function public.import_money_s3_accounting_v1(
  p_payload jsonb,
  p_file_name text,
  p_file_sha256 text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_entity public.accounting_entities%rowtype;
  v_period public.accounting_periods%rowtype;
  v_batch_id bigint;
  v_existing_batch public.accounting_import_batches%rowtype;
  v_item jsonb;
  v_line jsonb;
  v_account_id bigint;
  v_debit_account_id bigint;
  v_credit_account_id bigint;
  v_entry_id bigint;
  v_existing_entry public.accounting_journal_entries%rowtype;
  v_entry_hash text;
  v_entry_debit numeric(18,2);
  v_entry_credit numeric(18,2);
  v_entry_count integer := 0;
  v_line_count integer := 0;
  v_conflicts integer := 0;
  v_warnings jsonb := coalesce(p_payload->'warnings', '[]'::jsonb);
  v_start date := nullif(p_payload->>'accounting_year_start', '')::date;
  v_end date := nullif(p_payload->>'accounting_year_end', '')::date;
  v_agenda_id text := nullif(trim(p_payload->>'agenda_id'), '');
begin
  if not public.accounting_can_manage_v1() then
    raise exception 'Účetní import může provést pouze vedení nebo účetní role.';
  end if;
  if coalesce(p_payload->>'format', '') <> 'money_s3_native_xml' then
    raise exception 'Nepodporovaný formát účetního importu.';
  end if;
  if v_start is null or v_end is null or v_start > v_end then
    raise exception 'Money XML neobsahuje platné účetní období.';
  end if;
  if coalesce(p_file_name, '') = '' or coalesce(p_file_sha256, '') !~ '^[0-9a-f]{64}$' then
    raise exception 'Chybí název souboru nebo platný SHA-256 otisk.';
  end if;

  select * into v_entity
  from public.accounting_entities entity
  where entity.active
    and (v_agenda_id is null or entity.source_agenda_id = v_agenda_id or entity.source_agenda_id is null)
  order by (entity.source_agenda_id = v_agenda_id) desc nulls last, entity.id
  limit 1;

  if v_entity.id is null then
    raise exception 'V OLVENDU není založená aktivní účetní jednotka.';
  end if;

  if v_agenda_id is not null and v_entity.source_agenda_id is null then
    update public.accounting_entities
    set source_agenda_id = v_agenda_id
    where id = v_entity.id
    returning * into v_entity;
  end if;

  select * into v_existing_batch
  from public.accounting_import_batches batch
  where batch.entity_id = v_entity.id and batch.source_file_sha256 = p_file_sha256;

  if v_existing_batch.id is not null then
    return jsonb_build_object(
      'status', 'duplicate',
      'batch_id', v_existing_batch.id,
      'message', 'Tento přesný Money XML soubor už byl načten.',
      'entry_count', v_existing_batch.entry_count,
      'line_count', v_existing_batch.line_count
    );
  end if;

  insert into public.accounting_periods (entity_id, code, starts_on, ends_on)
  values (v_entity.id, extract(year from v_start)::text, v_start, v_end)
  on conflict (entity_id, starts_on, ends_on) do update set updated_at = now()
  returning * into v_period;

  if v_period.status = 'locked' then
    raise exception 'Účetní období % je uzamčené.', v_period.code;
  end if;

  insert into public.accounting_import_batches (
    entity_id, period_id, source_file_name, source_file_sha256, source_schema_version,
    source_agenda_id, source_exported_at, status, warnings, metadata, imported_by
  ) values (
    v_entity.id, v_period.id, p_file_name, p_file_sha256, p_payload->>'schema_version',
    v_agenda_id, nullif(p_payload->>'exported_at', '')::date, 'processing', v_warnings,
    jsonb_build_object('description', p_payload->>'description', 'export_abbreviation', p_payload->>'export_abbreviation'),
    auth.uid()
  ) returning id into v_batch_id;

  for v_item in select value from jsonb_array_elements(coalesce(p_payload->'accounts', '[]'::jsonb)) loop
    if coalesce(trim(v_item->>'code'), '') = '' then continue; end if;
    insert into public.accounting_accounts (
      period_id, code, name, kind, account_type, money_kind_code, money_type_code,
      money_subtype_code, tracks_balance, affects_income_tax, internal_account,
      technical_account, correction_account, source_incomplete, active, note
    ) values (
      v_period.id, trim(v_item->>'code'), coalesce(nullif(trim(v_item->>'name'), ''), trim(v_item->>'code')),
      coalesce(nullif(v_item->>'kind', ''), 'unspecified'), coalesce(nullif(v_item->>'account_type', ''), 'unspecified'),
      v_item->>'kind_code', v_item->>'type_code', v_item->>'subtype_code',
      coalesce((v_item->>'tracks_balance')::boolean, false), coalesce((v_item->>'affects_income_tax')::boolean, false),
      coalesce((v_item->>'internal')::boolean, false), coalesce((v_item->>'technical')::boolean, false),
      coalesce((v_item->>'correction')::boolean, false), false, true, nullif(v_item->>'note', '')
    )
    on conflict (period_id, code) do update set
      name = excluded.name, kind = excluded.kind, account_type = excluded.account_type,
      money_kind_code = excluded.money_kind_code, money_type_code = excluded.money_type_code,
      money_subtype_code = excluded.money_subtype_code, tracks_balance = excluded.tracks_balance,
      affects_income_tax = excluded.affects_income_tax, internal_account = excluded.internal_account,
      technical_account = excluded.technical_account, correction_account = excluded.correction_account,
      source_incomplete = false, active = true, note = excluded.note, updated_at = now();
  end loop;

  for v_item in select value from jsonb_array_elements(coalesce(p_payload->'preaccountings', '[]'::jsonb)) loop
    select id into v_debit_account_id from public.accounting_accounts
    where period_id = v_period.id and code = nullif(v_item->>'debit_account_code', '');
    select id into v_credit_account_id from public.accounting_accounts
    where period_id = v_period.id and code = nullif(v_item->>'credit_account_code', '');

    insert into public.accounting_preaccountings (
      period_id, code, document_type, description, debit_account_id, credit_account_id,
      debit_account_code, credit_account_code, vat_posting_code, follow_up_enabled,
      follow_up_price_type, follow_up_debit_account_code, follow_up_credit_account_code,
      vat_classification, active, note
    ) values (
      v_period.id, trim(v_item->>'code'), coalesce(nullif(v_item->>'document_type', ''), 'NN'),
      coalesce(nullif(v_item->>'description', ''), trim(v_item->>'code')),
      v_debit_account_id, v_credit_account_id, nullif(v_item->>'debit_account_code', ''),
      nullif(v_item->>'credit_account_code', ''), nullif(v_item->>'vat_posting_code', ''),
      coalesce((v_item->>'follow_up_enabled')::boolean, false), nullif(v_item->>'follow_up_price_type', ''),
      nullif(v_item->>'follow_up_debit_account_code', ''), nullif(v_item->>'follow_up_credit_account_code', ''),
      nullif(v_item->>'vat_classification', ''), true, nullif(v_item->>'note', '')
    )
    on conflict (period_id, code, document_type) do update set
      description = excluded.description, debit_account_id = excluded.debit_account_id,
      credit_account_id = excluded.credit_account_id, debit_account_code = excluded.debit_account_code,
      credit_account_code = excluded.credit_account_code, vat_posting_code = excluded.vat_posting_code,
      follow_up_enabled = excluded.follow_up_enabled, follow_up_price_type = excluded.follow_up_price_type,
      follow_up_debit_account_code = excluded.follow_up_debit_account_code,
      follow_up_credit_account_code = excluded.follow_up_credit_account_code,
      vat_classification = excluded.vat_classification, active = true, note = excluded.note, updated_at = now();
  end loop;

  for v_item in select value from jsonb_array_elements(coalesce(p_payload->'entries', '[]'::jsonb)) loop
    if nullif(v_item->>'entry_date', '')::date not between v_period.starts_on and v_period.ends_on then
      v_conflicts := v_conflicts + 1;
      v_warnings := v_warnings || jsonb_build_array('Doklad ' || coalesce(v_item->>'source_document_number', '?') || ' neleží v účetním období.');
      continue;
    end if;

    v_entry_hash := encode(digest(convert_to(v_item::text, 'UTF8'), 'sha256'), 'hex');
    v_entry_id := null;
    insert into public.accounting_journal_entries (
      period_id, import_batch_id, entry_date, taxable_date, description, source_type, source_key,
      source_document_number, external_id, source_payload_sha256, variable_symbol, currency,
      preaccounting_code, status
    ) values (
      v_period.id, v_batch_id, (v_item->>'entry_date')::date, nullif(v_item->>'taxable_date', '')::date,
      coalesce(nullif(v_item->>'description', ''), v_item->>'source_document_number'),
      v_item->>'source_type', v_item->>'source_key', nullif(v_item->>'source_document_number', ''),
      nullif(v_item->>'external_id', ''), v_entry_hash, nullif(v_item->>'variable_symbol', ''),
      upper(coalesce(nullif(v_item->>'currency', ''), 'CZK')), nullif(v_item->>'preaccounting_code', ''), 'imported'
    )
    on conflict (period_id, source_type, source_key) do nothing
    returning id into v_entry_id;

    if v_entry_id is null then
      select * into v_existing_entry from public.accounting_journal_entries
      where period_id = v_period.id and source_type = v_item->>'source_type' and source_key = v_item->>'source_key';
      if v_existing_entry.source_payload_sha256 is distinct from v_entry_hash then
        v_conflicts := v_conflicts + 1;
        v_warnings := v_warnings || jsonb_build_array('Doklad ' || coalesce(v_item->>'source_document_number', '?') || ' se proti staršímu importu změnil; původní stínový zápis zůstal zachovaný.');
      end if;
      continue;
    end if;

    v_entry_debit := 0;
    v_entry_credit := 0;
    for v_line in select value from jsonb_array_elements(coalesce(v_item->'lines', '[]'::jsonb)) loop
      select id into v_account_id from public.accounting_accounts
      where period_id = v_period.id and code = trim(v_line->>'account_code');

      if v_account_id is null then
        insert into public.accounting_accounts (period_id, code, name, source_incomplete)
        values (v_period.id, trim(v_line->>'account_code'), 'Doplnit z Money S3', true)
        on conflict (period_id, code) do update set source_incomplete = true
        returning id into v_account_id;
        v_warnings := v_warnings || jsonb_build_array('Účet ' || trim(v_line->>'account_code') || ' byl založen jako neúplný; načtěte účetní osnovu z Money.');
      end if;

      insert into public.accounting_journal_lines (
        entry_id, line_number, account_id, account_code, description, debit, credit,
        amount_currency, cost_center, job, activity, pairing_symbol, counterparty_company_id,
        vat_rate, price_type
      ) values (
        v_entry_id, (v_line->>'line_number')::integer, v_account_id, trim(v_line->>'account_code'),
        nullif(v_line->>'description', ''), coalesce((v_line->>'debit')::numeric, 0),
        coalesce((v_line->>'credit')::numeric, 0), nullif(v_line->>'amount_currency', '')::numeric,
        nullif(v_line->>'cost_center', ''), nullif(v_line->>'job', ''), nullif(v_line->>'activity', ''),
        nullif(v_line->>'pairing_symbol', ''), nullif(v_line->>'company_id', ''),
        nullif(v_line->>'vat_rate', '')::numeric, nullif(v_line->>'price_type', '')
      );
      v_entry_debit := v_entry_debit + coalesce((v_line->>'debit')::numeric, 0);
      v_entry_credit := v_entry_credit + coalesce((v_line->>'credit')::numeric, 0);
      v_line_count := v_line_count + 1;
    end loop;

    update public.accounting_journal_entries
    set status = case when abs(v_entry_debit - v_entry_credit) <= 0.01 and v_entry_debit > 0 then 'shadow_balanced' else 'needs_review' end
    where id = v_entry_id;
    if abs(v_entry_debit - v_entry_credit) > 0.01 or v_entry_debit <= 0 then
      v_conflicts := v_conflicts + 1;
      v_warnings := v_warnings || jsonb_build_array('Doklad ' || coalesce(v_item->>'source_document_number', '?') || ' není vyrovnaný.');
    end if;
    v_entry_count := v_entry_count + 1;
  end loop;

  update public.accounting_import_batches batch set
    status = case when v_conflicts > 0 or jsonb_array_length(v_warnings) > 0 then 'needs_review' else 'completed' end,
    account_count = jsonb_array_length(coalesce(p_payload->'accounts', '[]'::jsonb)),
    preaccounting_count = jsonb_array_length(coalesce(p_payload->'preaccountings', '[]'::jsonb)),
    entry_count = v_entry_count,
    line_count = v_line_count,
    debit_total = coalesce((p_payload#>>'{summary,debit}')::numeric, 0),
    credit_total = coalesce((p_payload#>>'{summary,credit}')::numeric, 0),
    warning_count = jsonb_array_length(v_warnings),
    warnings = v_warnings,
    completed_at = now()
  where batch.id = v_batch_id;

  insert into public.accounting_audit_log (entity_id, period_id, actor_user_id, action, object_type, object_id, detail)
  values (
    v_entity.id, v_period.id, auth.uid(), 'money_s3_xml_imported', 'accounting_import_batch', v_batch_id::text,
    jsonb_build_object('file_name', p_file_name, 'sha256', p_file_sha256, 'entries', v_entry_count, 'lines', v_line_count, 'conflicts', v_conflicts)
  );

  return jsonb_build_object(
    'status', case when v_conflicts > 0 or jsonb_array_length(v_warnings) > 0 then 'needs_review' else 'completed' end,
    'batch_id', v_batch_id,
    'period_id', v_period.id,
    'entry_count', v_entry_count,
    'line_count', v_line_count,
    'warning_count', jsonb_array_length(v_warnings),
    'message', 'Money XML byl načten pouze do stínového účetnictví OLVEND.'
  );
exception when others then
  if v_batch_id is not null then
    update public.accounting_import_batches
    set status = 'failed', warnings = warnings || jsonb_build_array(sqlerrm), warning_count = warning_count + 1, completed_at = now()
    where id = v_batch_id;
  end if;
  raise;
end;
$$;

create or replace view public.accounting_journal_overview_v1
with (security_invoker = true) as
select
  entry.id,
  entry.period_id,
  entry.import_batch_id,
  entry.entry_date,
  entry.taxable_date,
  entry.source_type,
  entry.source_document_number,
  entry.description,
  entry.variable_symbol,
  entry.currency,
  entry.preaccounting_code,
  entry.status,
  coalesce(sum(line.debit), 0)::numeric(18,2) as debit_total,
  coalesce(sum(line.credit), 0)::numeric(18,2) as credit_total,
  (coalesce(sum(line.debit), 0) - coalesce(sum(line.credit), 0))::numeric(18,2) as difference,
  count(line.id)::integer as line_count,
  entry.created_at
from public.accounting_journal_entries entry
left join public.accounting_journal_lines line on line.entry_id = entry.id
group by entry.id;

create or replace view public.accounting_trial_balance_v1
with (security_invoker = true) as
select
  account.period_id,
  account.id as account_id,
  account.code as account_code,
  account.name as account_name,
  account.kind,
  account.account_type,
  account.source_incomplete,
  coalesce(sum(line.debit), 0)::numeric(18,2) as debit_turnover,
  coalesce(sum(line.credit), 0)::numeric(18,2) as credit_turnover,
  (coalesce(sum(line.debit), 0) - coalesce(sum(line.credit), 0))::numeric(18,2) as balance
from public.accounting_accounts account
left join public.accounting_journal_lines line on line.account_id = account.id
group by account.id;

create or replace view public.accounting_control_summary_v1
with (security_invoker = true) as
select
  period.id as period_id,
  period.code as period_code,
  period.status as period_status,
  (select count(*)::integer from public.accounting_accounts account where account.period_id = period.id and account.active) as account_count,
  (select count(*)::integer from public.accounting_preaccountings preaccounting where preaccounting.period_id = period.id and preaccounting.active) as preaccounting_count,
  (select count(*)::integer from public.accounting_journal_entries entry where entry.period_id = period.id) as entry_count,
  (select count(*)::integer from public.accounting_journal_entries entry where entry.period_id = period.id and entry.status = 'needs_review') as review_entry_count,
  coalesce((select sum(overview.debit_total) from public.accounting_journal_overview_v1 overview where overview.period_id = period.id), 0)::numeric(18,2) as debit_total,
  coalesce((select sum(overview.credit_total) from public.accounting_journal_overview_v1 overview where overview.period_id = period.id), 0)::numeric(18,2) as credit_total
from public.accounting_periods period
;

