create or replace function public.accounting_can_manage_v1()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select
    coalesce(auth.role(), '') = 'service_role'
    or current_user in ('postgres', 'supabase_admin')
    or exists (
      select 1
      from public.employees employee
      where employee.auth_user_id = auth.uid()
        and employee.active is distinct from false
        and lower(coalesce(employee.role, '')) ~ '(admin|manager|manaž|manaz|vedouc|majitel|accountant|účet|ucet)'
    );
$$;

