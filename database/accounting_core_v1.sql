create or replace function public.accounting_protect_posted_v1()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_status text;
begin
  if tg_table_name = 'accounting_journal_entries' then
    v_status := old.status;
  else
    select entry.status into v_status
    from public.accounting_journal_entries entry
    where entry.id = old.entry_id;
  end if;

  if v_status in ('posted', 'reversed') then
    raise exception 'Zaúčtovaný nebo stornovaný zápis je neměnný; použijte opravný zápis.';
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

