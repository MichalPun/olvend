create or replace function public.finance_portal_scope_v1()
returns text language sql stable security definer set search_path=public,pg_temp as $$
  select case
    when public.finance_can_manage_v1() then 'internal'
    when exists (
      select 1 from public.finance_portal_users p
      where p.auth_user_id=auth.uid() and p.active
        and (p.access_from is null or p.access_from<=current_date)
        and (p.access_until is null or p.access_until>=current_date)
    ) then 'accountant'
    else null end;
$$;

