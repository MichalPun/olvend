create or replace function public.finance_can_manage_v1()
returns boolean language sql stable security definer set search_path=public,pg_temp as $$
  select coalesce(auth.role(),'')='service_role'
    or exists (
      select 1 from public.employees e
      where e.auth_user_id=auth.uid() and e.active is distinct from false
        and lower(coalesce(e.role,'')) ~ '(admin|manager|manaž|manaz|vedouc|majitel|finance|accountant|účet|ucet)'
    );
$$;

