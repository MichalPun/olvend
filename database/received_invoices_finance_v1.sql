create or replace function public.finance_assign_internal_number_v1()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare v_year text; v_seq integer;
begin
  if new.internal_number is not null then return new; end if;
  v_year:=to_char(coalesce(new.issue_date,current_date),'YY');
  perform pg_advisory_xact_lock(hashtext('finance-money-invoice-'||v_year));
  select coalesce(max(substring(internal_number from ('^FP'||v_year||'([0-9]+)$'))::integer),0)+1 into v_seq
  from public.finance_received_invoices where internal_number~('^FP'||v_year||'[0-9]+$');
  new.internal_number:='FP'||v_year||lpad(v_seq::text,4,'0');
  return new;
end; $$;
drop trigger if exists trg_finance_invoice_number on public.finance_received_invoices;
create trigger trg_finance_invoice_number before insert on public.finance_received_invoices for each row execute function public.finance_assign_internal_number_v1();

create or replace function public.finance_create_payment_batch_v1(p_invoice_ids bigint[],p_debtor_account text default 'CONFIGURE')
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_batch public.finance_payment_batches; v_count integer; v_total numeric(18,2); v_number text;
begin
  if not public.finance_can_manage_v1() then raise exception 'Přístup odepřen.' using errcode='42501'; end if;
  if coalesce(array_length(p_invoice_ids,1),0)=0 then raise exception 'Vyberte alespoň jednu fakturu.'; end if;
  if p_debtor_account='CONFIGURE' then raise exception 'Nejdřív nastavte účet plátce pro platební dávky.'; end if;
  if exists(select 1 from public.finance_received_invoices where id=any(p_invoice_ids) and (status not in ('ready_for_payment') or payment_status<>'unpaid' or coalesce(iban,bank_account) is null)) then
    raise exception 'Dávka obsahuje neschválenou, uhrazenou nebo neúplnou fakturu.';
  end if;
  perform pg_advisory_xact_lock(hashtext('finance-payment-batch-'||to_char(current_date,'YYYY')));
  select 'HP-'||to_char(current_date,'YYYY')||'-'||lpad((count(*)+1)::text,4,'0') into v_number from public.finance_payment_batches where created_at>=date_trunc('year',now());
  insert into public.finance_payment_batches(batch_number,debtor_account,requested_execution_date,created_by)
  values(v_number,p_debtor_account,current_date,auth.uid()) returning * into v_batch;
  insert into public.finance_payment_batch_items(batch_id,invoice_id,amount,creditor_account,creditor_iban,variable_symbol,message)
  select v_batch.id,i.id,i.total_amount,i.bank_account,i.iban,i.variable_symbol,coalesce(i.payment_message,i.document_number)
  from public.finance_received_invoices i where i.id=any(p_invoice_ids);
  select count(*),sum(amount) into v_count,v_total from public.finance_payment_batch_items where batch_id=v_batch.id;
  update public.finance_payment_batches set payment_count=v_count,total_amount=v_total,status='ready' where id=v_batch.id;
  update public.finance_received_invoices set status='in_payment_batch',payment_status='ordered',updated_at=now() where id=any(p_invoice_ids);
  return jsonb_build_object('id',v_batch.id,'batch_number',v_number,'payment_count',v_count,'total_amount',v_total,'status','ready');
end; $$;

create or replace view public.finance_received_invoice_overview_v1 with (security_invoker=true) as
select i.*,e.name||' '||e.surname owner,
  a.file_name attachment_name,a.storage_path attachment_path,a.sha256 attachment_sha256,
  coalesce((select sum(m.matched_amount) from public.finance_payment_matches m where m.invoice_id=i.id and m.status='confirmed'),0) matched_amount
from public.finance_received_invoices i
left join public.employees e on e.id=i.owner_employee_id
left join lateral(select x.file_name,x.storage_path,x.sha256 from public.finance_invoice_attachments x where x.invoice_id=i.id and x.kind='original' order by x.id limit 1)a on true;

create or replace function public.get_finance_dashboard_v1(p_month date)
returns jsonb language sql stable security definer set search_path=public,pg_temp as $$
  select case when public.finance_can_manage_v1() then jsonb_build_object(
    'open_amount',coalesce(sum(total_amount) filter(where payment_status not in ('paid','cancelled')),0),
    'open_count',count(*) filter(where payment_status not in ('paid','cancelled')),
    'overdue_amount',coalesce(sum(total_amount) filter(where payment_status not in ('paid','cancelled') and due_date<current_date),0),
    'overdue_count',count(*) filter(where payment_status not in ('paid','cancelled') and due_date<current_date),
    'due_soon_amount',coalesce(sum(total_amount) filter(where payment_status not in ('paid','cancelled') and due_date between current_date and current_date+7),0),
    'due_soon_count',count(*) filter(where payment_status not in ('paid','cancelled') and due_date between current_date and current_date+7),
    'paid_amount',coalesce(sum(total_amount) filter(where paid_at>=date_trunc('month',p_month)::date and paid_at<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'paid_count',count(*) filter(where paid_at>=date_trunc('month',p_month)::date and paid_at<(date_trunc('month',p_month)+interval '1 month')::date),
    'cost_net',coalesce(sum(net_amount) filter(where taxable_date>=date_trunc('month',p_month)::date and taxable_date<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'new_count',count(*) filter(where status='new'),
    'approval_count',count(*) filter(where status='approval'),
    'ready_count',count(*) filter(where status='ready_for_payment' and payment_status='unpaid'),
    'ordered_count',count(*) filter(where payment_status='ordered'),
    'handoff_count',count(*) filter(where handoff_status='ready')
  ) else null end from public.finance_received_invoices;
$$;

create or replace function public.finance_get_accounting_package_v1(p_package_id bigint)
returns jsonb language sql stable security definer set search_path=public,pg_temp as $$
  select case when public.finance_portal_scope_v1() is not null then jsonb_build_object(
    'package',to_jsonb(p),
    'documents',coalesce((select jsonb_agg(jsonb_build_object(
      'id',i.id,'internal_number',i.internal_number,'supplier_name',i.supplier_name,'document_number',i.document_number,
      'taxable_date',i.taxable_date,'currency',i.currency,'net_amount',i.net_amount,'vat_amount',i.vat_amount,'total_amount',i.total_amount,
      'cost_center',i.cost_center,'payment_status',i.payment_status,'paid_at',i.paid_at,'accountant_note',i.accountant_note,
      'attachment',jsonb_build_object('file_name',a.file_name,'sha256',a.sha256)
    ) order by i.taxable_date,i.internal_number)
    from public.finance_accounting_package_items pi
    join public.finance_received_invoices i on i.id=pi.invoice_id
    left join lateral(select x.file_name,x.sha256 from public.finance_invoice_attachments x where x.invoice_id=i.id and x.kind='original' order by x.id limit 1)a on true
    where pi.package_id=p.id), '[]'::jsonb)
  ) else null end
  from public.finance_accounting_packages p where p.id=p_package_id and p.status<>'draft';
$$;

