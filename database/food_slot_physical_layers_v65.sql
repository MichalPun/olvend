-- Potravinovy automat: trvaly cil pozice je oddelen od fyzickeho poradi
-- vyrobku v pruzine. Telemetrie spotrebovava vrstvy zepredu dozadu, ale
-- nikdy neprepise hlavni vyrobek planogramu.
begin;

alter table public.machine_planogram_slots
  add column if not exists primary_product_id bigint references public.products(id) on delete set null,
  add column if not exists primary_product_sku text,
  add column if not exists primary_product_name text;

update public.machine_planogram_slots slot
set primary_product_id = (
      select p.id from public.products p where p.sku=slot.product_sku
      order by p.active desc,p.id limit 1
    ),
    primary_product_sku = slot.product_sku,
    primary_product_name = slot.product_name
where slot.primary_product_sku is null
  and nullif(trim(slot.product_sku), '') is not null;

update public.machine_planogram_slots
set primary_product_sku = coalesce(primary_product_sku, product_sku),
    primary_product_name = coalesce(primary_product_name, product_name)
where primary_product_sku is null;

create index if not exists machine_planogram_slots_primary_product_idx
  on public.machine_planogram_slots(machine_id, primary_product_sku)
  where active is true;

create table if not exists public.machine_planogram_slot_layers (
  id bigint generated by default as identity primary key,
  planogram_slot_id bigint not null references public.machine_planogram_slots(id) on delete cascade,
  layer_order integer not null check (layer_order > 0),
  product_id bigint references public.products(id) on delete restrict,
  product_sku text not null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  expiry_date date,
  source text not null default 'operator',
  source_visit_id bigint references public.route_machine_visits(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(planogram_slot_id, layer_order)
);

create index if not exists machine_planogram_slot_layers_slot_idx
  on public.machine_planogram_slot_layers(planogram_slot_id, layer_order);

create table if not exists public.machine_planogram_slot_layer_consumptions (
  consumption_key text primary key,
  planogram_slot_id bigint not null references public.machine_planogram_slots(id) on delete cascade,
  requested_quantity integer not null check(requested_quantity>0),
  result jsonb not null,
  created_at timestamptz not null default now()
);
alter table public.machine_planogram_slot_layer_consumptions enable row level security;
revoke all on table public.machine_planogram_slot_layer_consumptions from public,anon,authenticated;

alter table public.machine_planogram_slot_layers enable row level security;

drop policy if exists "Allow read machine planogram slot layers" on public.machine_planogram_slot_layers;
create policy "Allow read machine planogram slot layers"
on public.machine_planogram_slot_layers for select to authenticated, anon using (true);

-- Prvni prevod zachova dosavadni dvouvrstvou evidenci. Neznamy zbytek se
-- priradi prednimu produktu, stejne jako jej dosud interpretovala aplikace.
with mixed as (
  select slot.id,
         greatest(0, least(coalesce(slot.current_units,0), coalesce(slot.changeover_old_units,0)::integer)) old_qty,
         greatest(0, least(
           coalesce(slot.current_units,0) - greatest(0, least(coalesce(slot.current_units,0), coalesce(slot.changeover_old_units,0)::integer)),
           coalesce(slot.changeover_new_units,0)::integer
         )) new_qty,
         coalesce(slot.current_units,0) total_qty,
         slot.product_sku, slot.product_name, slot.planned_product_sku, slot.planned_product_name,
         slot.expiry_date
  from public.machine_planogram_slots slot
  where slot.active is true
    and coalesce(slot.current_units,0) > 0
    and nullif(trim(slot.product_sku),'') is not null
    and nullif(trim(slot.planned_product_sku),'') is not null
    and slot.planned_product_sku is distinct from slot.product_sku
    and coalesce(slot.changeover_new_units,0) > 0
), normalized as (
  select mixed.*,
         old_qty + greatest(0,total_qty-old_qty-new_qty) front_qty
  from mixed
), layer_rows as (
  select id planogram_slot_id, 1 layer_order, product_sku, product_name,
         front_qty quantity, expiry_date
  from normalized where front_qty > 0
  union all
  select id, 2, planned_product_sku, coalesce(planned_product_name,planned_product_sku),
         new_qty, null::date
  from normalized where new_qty > 0
)
insert into public.machine_planogram_slot_layers(
  planogram_slot_id,layer_order,product_id,product_sku,product_name,quantity,expiry_date,source
)
select row.planogram_slot_id,row.layer_order,product.id,row.product_sku,row.product_name,row.quantity,row.expiry_date,'legacy_migration'
from layer_rows row
left join lateral (
  select p.id from public.products p where p.sku=row.product_sku order by p.active desc,p.id limit 1
) product on true
where not exists (
  select 1 from public.machine_planogram_slot_layers existing
  where existing.planogram_slot_id=row.planogram_slot_id
)
order by row.planogram_slot_id,row.layer_order;

insert into public.machine_planogram_slot_layers(
  planogram_slot_id,layer_order,product_id,product_sku,product_name,quantity,expiry_date,source
)
select slot.id,1,product.id,slot.product_sku,slot.product_name,slot.current_units,slot.expiry_date,'legacy_migration'
from public.machine_planogram_slots slot
left join lateral (
  select p.id from public.products p where p.sku=slot.product_sku order by p.active desc,p.id limit 1
) product on true
where slot.active is true
  and coalesce(slot.current_units,0)>0
  and nullif(trim(slot.product_sku),'') is not null
  and not exists (
    select 1 from public.machine_planogram_slot_layers existing
    where existing.planogram_slot_id=slot.id
  );

-- Po prevodu uz planned_product_* nesmi suplovat fyzickou druhou vrstvu.
-- Skutecna manazerska zmena bez nalozeneho druheho produktu zustava beze zmeny.
update public.machine_planogram_slots slot
set planned_product_sku=null,planned_product_name=null,planned_price_czk=null,
    changeover_old_units=null,changeover_new_units=null,changeover_started_at=null
where coalesce(slot.changeover_new_units,0)>0
  and exists(
    select 1 from public.machine_planogram_slot_layers layer
    where layer.planogram_slot_id=slot.id and layer.layer_order>1
  );

create or replace function public.replace_machine_planogram_slot_layers(
  p_slot_id bigint,
  p_layers jsonb,
  p_source_visit_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_slot public.machine_planogram_slots%rowtype;
  v_layer jsonb;
  v_order integer:=0;
  v_total integer:=0;
  v_product public.products%rowtype;
  v_front public.machine_planogram_slot_layers%rowtype;
  v_expiry date;
begin
  perform public.security_assert_active_employee();
  select * into strict v_slot from public.machine_planogram_slots where id=p_slot_id for update;
  if jsonb_typeof(coalesce(p_layers,'[]'::jsonb)) <> 'array' then
    raise exception 'Slozeni pruziny musi byt pole.';
  end if;

  delete from public.machine_planogram_slot_layers where planogram_slot_id=p_slot_id;
  for v_layer in select value from jsonb_array_elements(coalesce(p_layers,'[]'::jsonb))
  loop
    if coalesce((v_layer->>'quantity')::integer,0)<=0 then continue; end if;
    select * into v_product
    from public.products
    where id=nullif(v_layer->>'product_id','')::bigint
       or sku=nullif(trim(v_layer->>'product_sku'),'')
    order by (id=nullif(v_layer->>'product_id','')::bigint) desc,active desc,id
    limit 1;
    if not found then raise exception 'Produkt vrstvy nebyl nalezen.'; end if;
    v_order:=v_order+1;
    v_total:=v_total+(v_layer->>'quantity')::integer;
    insert into public.machine_planogram_slot_layers(
      planogram_slot_id,layer_order,product_id,product_sku,product_name,quantity,expiry_date,source,source_visit_id
    ) values (
      p_slot_id,v_order,v_product.id,v_product.sku,v_product.name,(v_layer->>'quantity')::integer,
      nullif(v_layer->>'expiry_date','')::date,'operator',p_source_visit_id
    );
  end loop;
  if v_total>coalesce(v_slot.capacity_units,v_total) then
    raise exception 'Soucet vrstev % ks prekrocil kapacitu % ks.',v_total,v_slot.capacity_units;
  end if;

  select * into v_front from public.machine_planogram_slot_layers
  where planogram_slot_id=p_slot_id order by layer_order limit 1;
  select min(expiry_date) into v_expiry from public.machine_planogram_slot_layers
  where planogram_slot_id=p_slot_id and expiry_date is not null;

  update public.machine_planogram_slots
  set product_sku=coalesce(v_front.product_sku,primary_product_sku,product_sku),
      product_name=coalesce(v_front.product_name,primary_product_name,product_name),
      primary_product_id=coalesce(primary_product_id,v_front.product_id),
      primary_product_sku=coalesce(primary_product_sku,v_front.product_sku,product_sku),
      primary_product_name=coalesce(primary_product_name,v_front.product_name,product_name),
      current_units=v_total,
      fill_percent=case when coalesce(capacity_units,0)>0 then round(v_total::numeric/capacity_units*100,2) else 0 end,
      expiry_date=v_expiry,
      planned_product_sku=null,planned_product_name=null,planned_price_czk=null,
      changeover_old_units=null,changeover_new_units=null,changeover_started_at=null
  where id=p_slot_id;

  return jsonb_build_object('slot_id',p_slot_id,'total_units',v_total,'layer_count',v_order);
end $$;

revoke all on function public.replace_machine_planogram_slot_layers(bigint,jsonb,bigint) from public;
grant execute on function public.replace_machine_planogram_slot_layers(bigint,jsonb,bigint) to authenticated,service_role;

create or replace function public.consume_machine_planogram_slot_layers(
  p_slot_id bigint,p_quantity integer,p_consumption_key text
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_slot public.machine_planogram_slots%rowtype;
  v_layer public.machine_planogram_slot_layers%rowtype;
  v_needed integer:=greatest(0,coalesce(p_quantity,0));
  v_take integer;
  v_part integer:=0;
  v_parts jsonb:='[]'::jsonb;
  v_remaining integer;
  v_front public.machine_planogram_slot_layers%rowtype;
  v_expiry date;
  v_result jsonb;
begin
  if nullif(trim(p_consumption_key),'') is null then raise exception 'Chybi idempotencni klic prodeje.'; end if;
  select result into v_result from public.machine_planogram_slot_layer_consumptions
  where consumption_key=p_consumption_key;
  if found then return v_result; end if;
  select * into strict v_slot from public.machine_planogram_slots where id=p_slot_id for update;
  if not exists(select 1 from public.machine_planogram_slot_layers where planogram_slot_id=p_slot_id) then
    return jsonb_build_object('handled',false);
  end if;
  for v_layer in
    select * from public.machine_planogram_slot_layers
    where planogram_slot_id=p_slot_id order by layer_order for update
  loop
    exit when v_needed<=0;
    v_take:=least(v_needed,v_layer.quantity);
    if v_take<=0 then continue; end if;
    v_part:=v_part+1;
    v_parts:=v_parts||jsonb_build_array(jsonb_build_object(
      'event_part',v_part,'product_id',v_layer.product_id,'product_sku',v_layer.product_sku,
      'product_name',v_layer.product_name,'quantity',v_take,'expiry_date',v_layer.expiry_date
    ));
    if v_take=v_layer.quantity then
      delete from public.machine_planogram_slot_layers where id=v_layer.id;
    else
      update public.machine_planogram_slot_layers
      set quantity=quantity-v_take,updated_at=now() where id=v_layer.id;
    end if;
    v_needed:=v_needed-v_take;
  end loop;
  if v_needed>0 then
    v_part:=v_part+1;
    v_parts:=v_parts||jsonb_build_array(jsonb_build_object(
      'event_part',v_part,'product_id',coalesce(v_slot.primary_product_id,null),
      'product_sku',coalesce(v_slot.primary_product_sku,v_slot.product_sku),
      'product_name',coalesce(v_slot.primary_product_name,v_slot.product_name),
      'quantity',v_needed,'stock_discrepancy',true
    ));
  end if;

  with ordered as (
    select id,row_number() over(order by layer_order,id) next_order
    from public.machine_planogram_slot_layers where planogram_slot_id=p_slot_id
  )
  update public.machine_planogram_slot_layers layer set layer_order=ordered.next_order
  from ordered where layer.id=ordered.id;

  select coalesce(sum(quantity),0)::integer,min(expiry_date)
  into v_remaining,v_expiry
  from public.machine_planogram_slot_layers where planogram_slot_id=p_slot_id;
  select * into v_front from public.machine_planogram_slot_layers
  where planogram_slot_id=p_slot_id order by layer_order limit 1;

  update public.machine_planogram_slots
  set product_sku=coalesce(v_front.product_sku,primary_product_sku,product_sku),
      product_name=coalesce(v_front.product_name,primary_product_name,product_name),
      current_units=v_remaining,
      fill_percent=case when coalesce(capacity_units,0)>0 then round(v_remaining::numeric/capacity_units*100,2) else 0 end,
      expiry_date=v_expiry,
      planned_product_sku=null,planned_product_name=null,planned_price_czk=null,
      changeover_old_units=null,changeover_new_units=null,changeover_started_at=null
  where id=p_slot_id;

  v_result:=jsonb_build_object('handled',true,'parts',v_parts,'remaining_units',v_remaining,
    'front_product_sku',coalesce(v_front.product_sku,v_slot.primary_product_sku,v_slot.product_sku));
  insert into public.machine_planogram_slot_layer_consumptions(
    consumption_key,planogram_slot_id,requested_quantity,result
  ) values(p_consumption_key,p_slot_id,greatest(1,p_quantity),v_result)
  on conflict(consumption_key) do nothing;
  return v_result;
end $$;

revoke all on function public.consume_machine_planogram_slot_layers(bigint,integer,text) from public,anon,authenticated;
grant execute on function public.consume_machine_planogram_slot_layers(bigint,integer,text) to service_role;

-- Databazova ochrana rozmanitosti sleduje trvaly cil pozice, nikoli docasny
-- vyrobek, ktery je prave vpredu v pruzine.
create or replace function public.guard_basic_fresh_planogram_uniqueness_v62()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_is_fresh boolean; v_fresh_count integer; v_unique_count integer; v_sku text;
begin
  v_sku:=coalesce(new.primary_product_sku,new.product_sku);
  if tg_op='UPDATE'
     and new.machine_id is not distinct from old.machine_id
     and coalesce(new.primary_product_sku,new.product_sku) is not distinct from coalesce(old.primary_product_sku,old.product_sku)
     and new.active is not distinct from old.active then return new; end if;
  if new.active is not true or v_sku is null then return new; end if;
  select exists(select 1 from public.products product where product.sku=v_sku and (
    lower(coalesce(product.product_category,''))='food_ready' or lower(coalesce(product.name,'')) similar to '%(baget|strips)%'
  )) into v_is_fresh;
  if not v_is_fresh then return new; end if;
  with fresh_after as (
    select coalesce(slot.primary_product_sku,slot.product_sku) sku
    from public.machine_planogram_slots slot
    join public.products product on product.sku=coalesce(slot.primary_product_sku,slot.product_sku)
    where slot.machine_id=new.machine_id and slot.active is true and slot.id<>coalesce(new.id,-1)
      and (lower(coalesce(product.product_category,''))='food_ready' or lower(coalesce(product.name,'')) similar to '%(baget|strips)%')
    union all select v_sku
  ) select count(*),count(distinct sku) into v_fresh_count,v_unique_count from fresh_after;
  if v_fresh_count between 2 and 3 and v_unique_count<v_fresh_count then
    raise exception 'Zakladni automat musi mit rozdilne druhy baget. Docasnou fyzickou nahradu zapis do vrstev pruziny.';
  end if;
  return new;
end $$;

drop trigger if exists guard_basic_fresh_planogram_uniqueness_v62 on public.machine_planogram_slots;
create trigger guard_basic_fresh_planogram_uniqueness_v62
before insert or update of machine_id,primary_product_sku,active on public.machine_planogram_slots
for each row execute function public.guard_basic_fresh_planogram_uniqueness_v62();

commit;
notify pgrst,'reload schema';
