create or replace function public.finance_normalize_match_key_v2(p_value text)
returns text language sql immutable set search_path=public,pg_temp as $$
  select regexp_replace(lower(coalesce(p_value,'')),'[^a-z0-9]+','','g');
$$;

create or replace function public.finance_text_has_match_key_v2(p_haystack text,p_key text)
returns boolean language sql immutable set search_path=public,pg_temp as $$
  select case
    when length(public.finance_normalize_match_key_v2(p_key))<6 then false
    when public.finance_normalize_match_key_v2(p_key) ~ '^[0-9]+$' then
      lower(coalesce(p_haystack,'')) ~ ('(^|[^0-9])'||public.finance_normalize_match_key_v2(p_key)||'([^0-9]|$)')
    else position(public.finance_normalize_match_key_v2(p_key) in public.finance_normalize_match_key_v2(p_haystack))>0
  end;
$$;

create or replace function public.finance_import_money_received_invoices_v2(
  p_rows jsonb,
  p_file_name text,
  p_file_sha256 text,
  p_exported_at date,
  p_total_rows integer,
  p_is_final boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_row jsonb;
  v_invoice_id bigint;
  v_queue public.finance_document_intake_queue%rowtype;
  v_total numeric(18,2);
  v_remaining numeric(18,2);
  v_payment_status text;
  v_status text;
  v_processed integer := 0;
  v_matched integer := 0;
  v_batch_count integer;
  v_batch_unpaid integer;
  v_batch_zero integer;
  v_batch_matched integer;
begin
  if not public.finance_can_manage_v1() then
    raise exception 'Import Money může provést pouze vedení Financí.' using errcode='42501';
  end if;
  if jsonb_typeof(p_rows)<>'array' or jsonb_array_length(p_rows)>100 then
    raise exception 'Jedna importní dávka musí obsahovat pole nejvýše 100 faktur.';
  end if;
  if coalesce(p_file_name,'')='' or coalesce(p_file_sha256,'') !~ '^[0-9a-f]{64}$' then
    raise exception 'Chybí název Money XML nebo platný SHA-256 otisk.';
  end if;

  for v_row in select value from jsonb_array_elements(p_rows) loop
    v_total := coalesce((v_row->>'total_amount')::numeric,0);
    v_remaining := coalesce((v_row->>'remaining_amount')::numeric,0);
    v_payment_status := case
      when abs(v_total)<0.01 then 'cancelled'
      when abs(v_remaining)<0.01 then 'paid'
      when abs(v_remaining)<abs(v_total)-0.01 then 'partially_paid'
      else 'unpaid'
    end;
    v_status := case
      when v_payment_status='cancelled' then 'cancelled'
      when v_payment_status='paid' then 'exported'
      else 'ready_for_payment'
    end;

    insert into public.finance_received_invoices (
      internal_number,source_provider,source_external_id,source_received_at,source_payload,
      supplier_name,supplier_company_id,supplier_tax_id,document_number,document_type,
      issue_date,taxable_date,due_date,received_date,currency,exchange_rate,
      net_amount,vat_amount,total_amount,bank_account,bank_code,variable_symbol,
      extraction_confidence,status,payment_status,handoff_status,paid_at,note,
      money_guid,money_internal_number,money_series,money_series_number,money_partner_guid,
      money_remaining_amount,money_source_file_sha256,money_imported_at,money_payment_method
    ) values (
      nullif(v_row->>'money_internal_number',''),'money_s3',v_row->>'money_guid',now(),
      jsonb_build_object('description',v_row->>'description','remaining_amount',v_remaining,'import','Money S3 přijaté faktury'),
      coalesce(nullif(v_row->>'supplier_name',''),'Neznámý dodavatel'),nullif(v_row->>'supplier_company_id',''),nullif(v_row->>'supplier_tax_id',''),
      coalesce(nullif(v_row->>'document_number',''),nullif(v_row->>'money_internal_number',''),'Bez čísla'),
      coalesce(nullif(v_row->>'document_type',''),'invoice'),
      nullif(v_row->>'issue_date','')::date,nullif(v_row->>'taxable_date','')::date,nullif(v_row->>'due_date','')::date,
      nullif(v_row->>'received_date','')::date,upper(coalesce(nullif(v_row->>'currency',''),'CZK')),
      greatest(coalesce((v_row->>'exchange_rate')::numeric,1),0.00000001),
      coalesce((v_row->>'net_amount')::numeric,0),coalesce((v_row->>'vat_amount')::numeric,0),v_total,
      nullif(v_row->>'bank_account',''),nullif(v_row->>'bank_code',''),nullif(v_row->>'variable_symbol',''),
      100,v_status,v_payment_status,'accepted',
      case when v_payment_status='paid' then nullif(v_row->>'paid_date','')::date else null end,
      'Evidence převzatá z Money S3. Účetní zařazení zůstává v Money.',
      v_row->>'money_guid',nullif(v_row->>'money_internal_number',''),nullif(v_row->>'money_series',''),
      nullif(v_row->>'money_series_number','')::integer,nullif(v_row->>'money_partner_guid',''),
      v_remaining,p_file_sha256,now(),nullif(v_row->>'payment_method','')
    )
    on conflict(source_provider,source_external_id) do update set
      internal_number=excluded.internal_number,source_payload=excluded.source_payload,
      supplier_name=excluded.supplier_name,supplier_company_id=excluded.supplier_company_id,supplier_tax_id=excluded.supplier_tax_id,
      document_number=excluded.document_number,document_type=excluded.document_type,
      issue_date=excluded.issue_date,taxable_date=excluded.taxable_date,due_date=excluded.due_date,received_date=excluded.received_date,
      currency=excluded.currency,exchange_rate=excluded.exchange_rate,net_amount=excluded.net_amount,vat_amount=excluded.vat_amount,total_amount=excluded.total_amount,
      bank_account=excluded.bank_account,bank_code=excluded.bank_code,variable_symbol=excluded.variable_symbol,
      payment_status=excluded.payment_status,
      status=case when excluded.payment_status in ('paid','cancelled') then excluded.status
        when finance_received_invoices.status in ('approval','rejected','in_payment_batch') then finance_received_invoices.status
        else excluded.status end,
      handoff_status='accepted',paid_at=excluded.paid_at,
      money_guid=excluded.money_guid,money_internal_number=excluded.money_internal_number,money_series=excluded.money_series,
      money_series_number=excluded.money_series_number,money_partner_guid=excluded.money_partner_guid,
      money_remaining_amount=excluded.money_remaining_amount,money_source_file_sha256=excluded.money_source_file_sha256,
      money_imported_at=now(),money_payment_method=excluded.money_payment_method,updated_at=now()
    returning id into v_invoice_id;

    for v_queue in
      select q.* from public.finance_document_intake_queue q
      where q.invoice_id is null and q.status in ('queued','needs_review')
        and (
          public.finance_text_has_match_key_v2(coalesce(q.file_name,'')||' '||coalesce(q.subject,''),v_row->>'document_number')
          or public.finance_text_has_match_key_v2(coalesce(q.file_name,'')||' '||coalesce(q.subject,''),v_row->>'variable_symbol')
          or public.finance_text_has_match_key_v2(coalesce(q.file_name,'')||' '||coalesce(q.subject,''),v_row->>'money_internal_number')
        )
      order by q.id
    loop
      insert into public.finance_invoice_attachments(
        invoice_id,kind,storage_bucket,storage_path,file_name,mime_type,size_bytes,sha256,immutable,uploaded_by
      ) values (
        v_invoice_id,
        case when lower(v_queue.file_name) ~ '(upom|remind|vyzva|výzva)' then 'supporting' else 'original' end,
        'finance-private',v_queue.storage_path,v_queue.file_name,v_queue.mime_type,v_queue.size_bytes,v_queue.sha256,true,auth.uid()
      ) on conflict(invoice_id,sha256) do nothing;
      update public.finance_document_intake_queue set
        invoice_id=v_invoice_id,status='invoice_created',extraction_confidence=99,
        extracted_payload=coalesce(extracted_payload,'{}'::jsonb)||jsonb_build_object('matched_by','money_s3_number','money_guid',v_row->>'money_guid'),
        processed_at=now(),error_message=null
      where id=v_queue.id;
      v_matched := v_matched+1;
    end loop;
    v_processed := v_processed+1;
  end loop;

  if p_is_final then
    select count(*),count(*) filter(where payment_status not in ('paid','cancelled')),
      count(*) filter(where abs(total_amount)<0.01)
    into v_batch_count,v_batch_unpaid,v_batch_zero
    from public.finance_received_invoices where money_source_file_sha256=p_file_sha256;

    select count(*) into v_batch_matched
    from public.finance_invoice_attachments a
    join public.finance_received_invoices i on i.id=a.invoice_id
    where i.money_source_file_sha256=p_file_sha256;

    insert into public.finance_money_invoice_imports(
      source_file_name,source_file_sha256,exported_at,invoice_count,unpaid_count,
      zero_amount_count,matched_attachment_count,status,imported_by,updated_at
    ) values (
      p_file_name,p_file_sha256,p_exported_at,coalesce(v_batch_count,p_total_rows),v_batch_unpaid,
      v_batch_zero,v_batch_matched,'completed',auth.uid(),now()
    ) on conflict(source_file_sha256) do update set
      source_file_name=excluded.source_file_name,exported_at=excluded.exported_at,
      invoice_count=excluded.invoice_count,unpaid_count=excluded.unpaid_count,
      zero_amount_count=excluded.zero_amount_count,matched_attachment_count=excluded.matched_attachment_count,
      status='completed',imported_by=excluded.imported_by,updated_at=now();
  end if;

  return jsonb_build_object('processed',v_processed,'matched_attachments',v_matched,'final',p_is_final);
end;
$$;

grant select on table public.finance_money_invoice_imports to authenticated;
revoke all on function public.finance_import_money_received_invoices_v2(jsonb,text,text,date,integer,boolean) from public,anon;
grant execute on function public.finance_import_money_received_invoices_v2(jsonb,text,text,date,integer,boolean) to authenticated,service_role;

