  ] loop
    execute format('drop policy if exists control_active_employee_access on public.%I', v_table);
    execute format(
      'create policy control_active_employee_access on public.%I for all to authenticated using (public.security_active_employee()) with check (public.security_active_employee())',
      v_table
    );
  end loop;
end $$;

