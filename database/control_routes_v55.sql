begin;

-- Kontrolni trasy jsou zamerne oddelene od route_plans a route_plan_stops.
-- Modul kontroly nesmi vytvaret, uzavirat ani jinak ovlivnovat doplnovaci trasu.

create table if not exists public.control_routes (
  id bigint generated by default as identity primary key,
  name text not null,
  control_type text not null default 'regular'
    check (control_type in ('regular', 'follow_up', 'complaint', 'extraordinary')),
  planned_date date not null,
  planned_start_time time null,
  assigned_employee_id uuid not null references public.employees(id) on delete restrict,
  status text not null default 'draft'
    check (status in ('draft', 'published', 'in_progress', 'completed', 'cancelled')),
  instructions text null,
  checklist_config jsonb not null default '{}'::jsonb,
  rule_config jsonb not null default '{}'::jsonb,
  published_at timestamptz null,
  started_at timestamptz null,
  completed_at timestamptz null,
  cancelled_at timestamptz null,
  created_by uuid null references public.employees(id) on delete set null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.control_route_stops (
  id bigint generated by default as identity primary key,
  control_route_id bigint not null references public.control_routes(id) on delete cascade,
  location_id bigint not null references public.locations(id) on delete restrict,
  stop_order integer not null check (stop_order > 0),
  status text not null default 'planned'
    check (status in ('planned', 'in_progress', 'completed', 'skipped')),
  location_name_snapshot text not null,
  address_snapshot text null,
  city_snapshot text null,
  latitude_snapshot numeric null,
  longitude_snapshot numeric null,
  instruction text null,
  started_at timestamptz null,
  completed_at timestamptz null,
  skipped_at timestamptz null,
  skip_reason text null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (control_route_id, stop_order),
  unique (control_route_id, location_id)
);

create table if not exists public.control_route_machines (
  id bigint generated by default as identity primary key,
  control_route_stop_id bigint not null references public.control_route_stops(id) on delete cascade,
  machine_id bigint not null references public.machines(id) on delete restrict,
  machine_kind text not null default 'other'
    check (machine_kind in ('coffee', 'food', 'other')),
  status text not null default 'planned'
    check (status in ('planned', 'in_progress', 'completed', 'skipped')),
  evidence_number_snapshot bigint null,
  machine_name_snapshot text not null,
  checklist_config jsonb not null default '{}'::jsonb,
  snapshot jsonb not null default '{}'::jsonb,
  started_at timestamptz null,
  completed_at timestamptz null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (control_route_stop_id, machine_id)
);

create table if not exists public.control_check_results (
  id bigint generated by default as identity primary key,
  control_route_id bigint not null references public.control_routes(id) on delete cascade,
  control_route_stop_id bigint not null references public.control_route_stops(id) on delete cascade,
  control_route_machine_id bigint null references public.control_route_machines(id) on delete cascade,
  scope text not null check (scope in ('place', 'machine', 'customer', 'summary')),
  item_key text not null,
  item_label text not null,
  status text not null default 'pending'
    check (status in ('pending', 'ok', 'finding', 'not_applicable')),
  note text null,
  measured_value numeric null,
  measure_unit text null,
  value_source text null check (value_source in ('manual', 'telemetry') or value_source is null),
  metadata jsonb not null default '{}'::jsonb,
  checked_by uuid null references public.employees(id) on delete set null,
  checked_at timestamptz null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create unique index if not exists control_check_results_unique_item_idx
  on public.control_check_results(control_route_stop_id, coalesce(control_route_machine_id, 0), scope, item_key);

create table if not exists public.control_findings (
  id bigint generated by default as identity primary key,
  control_route_id bigint not null references public.control_routes(id) on delete cascade,
  control_route_stop_id bigint not null references public.control_route_stops(id) on delete cascade,
  control_route_machine_id bigint null references public.control_route_machines(id) on delete set null,
  control_check_result_id bigint null references public.control_check_results(id) on delete set null,
  category text not null,
  severity text not null default 'medium'
    check (severity in ('low', 'medium', 'high', 'critical')),
  description text not null,
  resolution_type text not null default 'task'
    check (resolution_type in ('fixed_now', 'task')),
  resolution_note text null,
  assigned_employee_id uuid null references public.employees(id) on delete set null,
  assigned_external_name text null,
  due_date date null,
  operation_decision text not null default 'continue'
    check (operation_decision in ('continue', 'limited', 'stop')),
  status text not null default 'open'
    check (status in ('open', 'in_progress', 'resolved', 'cancelled')),
  context_snapshot jsonb not null default '{}'::jsonb,
  resolved_at timestamptz null,
  resolved_by uuid null references public.employees(id) on delete set null,
  created_by uuid null references public.employees(id) on delete set null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.control_finding_photos (
  id bigint generated by default as identity primary key,
  control_finding_id bigint not null references public.control_findings(id) on delete cascade,
  storage_path text not null,
  file_name text null,
  mime_type text null,
  created_by uuid null references public.employees(id) on delete set null,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.control_machine_adjustments (
  id bigint generated by default as identity primary key,
  control_route_id bigint not null references public.control_routes(id) on delete cascade,
  control_route_stop_id bigint not null references public.control_route_stops(id) on delete cascade,
  control_route_machine_id bigint not null references public.control_route_machines(id) on delete cascade,
  machine_id bigint not null references public.machines(id) on delete restrict,
  planogram_slot_id bigint null references public.machine_planogram_slots(id) on delete set null,
  adjustment_type text not null check (adjustment_type in ('price', 'stock', 'product', 'position')),
  before_value jsonb not null default '{}'::jsonb,
  after_value jsonb not null default '{}'::jsonb,
  note text null,
  status text not null default 'recorded'
    check (status in ('recorded', 'applied', 'rejected')),
  applied_at timestamptz null,
  created_by uuid null references public.employees(id) on delete set null,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists control_routes_employee_date_idx on public.control_routes(assigned_employee_id, planned_date, status);
create index if not exists control_routes_status_date_idx on public.control_routes(status, planned_date);
create index if not exists control_route_stops_route_idx on public.control_route_stops(control_route_id, stop_order);
create index if not exists control_route_stops_location_idx on public.control_route_stops(location_id, completed_at desc);
create index if not exists control_route_machines_stop_idx on public.control_route_machines(control_route_stop_id);
create index if not exists control_route_machines_machine_idx on public.control_route_machines(machine_id, completed_at desc);
create index if not exists control_check_results_route_idx on public.control_check_results(control_route_id, control_route_stop_id);
create index if not exists control_findings_open_idx on public.control_findings(status, due_date) where status in ('open', 'in_progress');

create or replace function public.touch_control_module_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists trg_control_routes_updated_at on public.control_routes;
