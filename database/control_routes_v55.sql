for each row execute function public.touch_control_module_updated_at();

create or replace function public.create_control_route_v55(p_payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_route_id bigint;
  v_stop_id bigint;
  v_stop jsonb;
  v_machine jsonb;
  v_employee uuid;
  v_creator uuid;
  v_status text;
begin
  if not public.security_active_employee() then
    raise exception 'Přístup vyžaduje aktivní zaměstnanecký účet.' using errcode = '42501';
  end if;

  v_creator := public.current_employee_id();
  v_employee := nullif(p_payload->>'assigned_employee_id', '')::uuid;
  if v_employee is null or not exists (select 1 from public.employees where id = v_employee and active is true) then
    raise exception 'Vyberte aktivního kontrolora.';
  end if;
  if jsonb_array_length(coalesce(p_payload->'stops', '[]'::jsonb)) = 0 then
    raise exception 'Kontrolní trasa musí obsahovat alespoň jednu lokalitu.';
  end if;

  v_status := case when coalesce((p_payload->>'publish')::boolean, false) then 'published' else 'draft' end;
  insert into public.control_routes (
    name, control_type, planned_date, planned_start_time, assigned_employee_id,
    status, instructions, checklist_config, rule_config, published_at, created_by
  ) values (
    nullif(trim(p_payload->>'name'), ''),
    coalesce(nullif(p_payload->>'control_type', ''), 'regular'),
    (p_payload->>'planned_date')::date,
    nullif(p_payload->>'planned_start_time', '')::time,
    v_employee,
    v_status,
    nullif(trim(p_payload->>'instructions'), ''),
    coalesce(p_payload->'checklist_config', '{}'::jsonb),
    coalesce(p_payload->'rule_config', '{}'::jsonb),
    case when v_status = 'published' then timezone('utc', now()) else null end,
    v_creator
  ) returning id into v_route_id;

  for v_stop in select value from jsonb_array_elements(p_payload->'stops')
  loop
    if not exists (select 1 from public.locations where id = (v_stop->>'location_id')::bigint and active is true) then
      raise exception 'Lokalita % není aktivní.', v_stop->>'location_id';
    end if;
    insert into public.control_route_stops (
      control_route_id, location_id, stop_order, location_name_snapshot,
      address_snapshot, city_snapshot, latitude_snapshot, longitude_snapshot, instruction
    )
    select v_route_id, l.id, (v_stop->>'stop_order')::integer, l.name,
      l.address, l.city, l.latitude, l.longitude, nullif(trim(v_stop->>'instruction'), '')
    from public.locations l where l.id = (v_stop->>'location_id')::bigint
    returning id into v_stop_id;

    for v_machine in select value from jsonb_array_elements(coalesce(v_stop->'machines', '[]'::jsonb))
    loop
      insert into public.control_route_machines (
        control_route_stop_id, machine_id, machine_kind, evidence_number_snapshot,
        machine_name_snapshot, checklist_config, snapshot
      )
      select v_stop_id, m.id,
        case
          when lower(coalesce(m.machine_type, '')) ~ '(coffee|káv|kav)' then 'coffee'
          when lower(coalesce(m.machine_type, '')) ~ '(food|snack|potrav)' then 'food'
          else 'other'
        end,
        m.evidence_number, m.name,
        coalesce(v_machine->'checklist_config', '{}'::jsonb),
        jsonb_build_object('machine_type', m.machine_type, 'brand', m.brand, 'model', m.model)
      from public.machines m
      where m.id = (v_machine->>'machine_id')::bigint
        and m.location_id = (v_stop->>'location_id')::bigint
        and m.active is true;
      if not found then
        raise exception 'Automat % není aktivní na vybrané lokalitě.', v_machine->>'machine_id';
      end if;
    end loop;
  end loop;

  return v_route_id;
end;
$$;

create or replace function public.start_control_route_v55(p_route_id bigint)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare v_employee uuid := public.current_employee_id();
begin
  if not public.security_active_employee() then raise exception 'Neaktivní účet.' using errcode = '42501'; end if;
  update public.control_routes
  set status = 'in_progress', started_at = coalesce(started_at, timezone('utc', now()))
  where id = p_route_id and assigned_employee_id = v_employee and status in ('published', 'in_progress');
  if not found then raise exception 'Kontrolní trasu nelze zahájit nebo vám není přiřazena.'; end if;
end;
$$;

create or replace function public.complete_control_route_v55(p_route_id bigint)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare v_employee uuid := public.current_employee_id();
begin
  if exists (
    select 1 from public.control_route_stops
    where control_route_id = p_route_id and status not in ('completed', 'skipped')
  ) then raise exception 'Nejdříve uzavřete nebo přeskočte všechny kontrolní zastávky.'; end if;
  update public.control_routes
  set status = 'completed', completed_at = timezone('utc', now())
  where id = p_route_id and assigned_employee_id = v_employee and status = 'in_progress';
  if not found then raise exception 'Kontrolní trasu nelze dokončit.'; end if;
end;
$$;

