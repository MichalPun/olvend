create table if not exists public.operational_requests (
  id bigint generated by default as identity primary key,
  request_kind text not null
    check (request_kind in ('equipment', 'vehicle_service', 'partner_delivery')),
  status text not null default 'new'
    check (status in (
      'new',
      'in_progress',
      'warehouse_queue',
      'picking',
      'ready',
      'billing_ready',
      'invoiced',
      'completed',
      'cancelled'
    )),
  title text not null,
  note text,
  need_timing text,
  employee_id uuid references public.employees (id) on delete set null,
  vehicle_id bigint references public.vehicles (id) on delete set null,
  warehouse_id bigint references public.warehouses (id) on delete set null,
  business_contact_id bigint references public.business_contacts (id) on delete set null,
  assigned_to uuid references public.employees (id) on delete set null,
  issued_by uuid references public.employees (id) on delete set null,
  issued_at timestamp with time zone,
  invoiced_at timestamp with time zone,
  invoice_id bigint,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create index if not exists operational_requests_status_idx
  on public.operational_requests (status, created_at desc);

create index if not exists operational_requests_employee_idx
  on public.operational_requests (employee_id, created_at desc);

create index if not exists operational_requests_kind_idx
  on public.operational_requests (request_kind, status);

create index if not exists operational_requests_partner_idx
  on public.operational_requests (business_contact_id, created_at desc);

create table if not exists public.operational_request_items (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.operational_requests (id) on delete cascade,
  product_id bigint references public.products (id) on delete set null,
  product_name text not null,
  sku text,
  unit text not null default 'ks',
  requested_quantity numeric(12,3) not null default 0 check (requested_quantity >= 0),
  issued_quantity numeric(12,3) check (issued_quantity is null or issued_quantity >= 0),
  unit_price_without_vat numeric(12,2),
  vat_rate numeric(5,2),
  note text,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);

create index if not exists operational_request_items_request_idx
  on public.operational_request_items (request_id);

create index if not exists operational_request_items_product_idx
  on public.operational_request_items (product_id);

