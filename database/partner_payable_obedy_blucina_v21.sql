-- Obedy Blucina: OLVEND sends monthly evidence, the partner invoices OLVEND.

begin;

alter table public.partner_billing_profiles
  add column if not exists billing_direction text not null default 'from_partner',
  add column if not exists rate_includes_vat boolean not null default false;

alter table public.partner_billing_profiles
  drop constraint if exists partner_billing_profiles_billing_direction_check;

alter table public.partner_billing_profiles
  add constraint partner_billing_profiles_billing_direction_check
  check (billing_direction in ('from_partner', 'to_partner'));

create table if not exists public.partner_settlement_reports (
  id bigint generated by default as identity primary key,
  location_id bigint not null references public.locations (id) on delete cascade,
  business_contact_id bigint references public.business_contacts (id) on delete set null,
  billing_direction text not null check (billing_direction in ('from_partner', 'to_partner')),
  period_month date not null,
  quantity numeric(14,3) not null default 0,
  unit_gross_rate numeric(12,4) not null default 0,
  vat_rate numeric(5,2) not null default 21,
  net_amount numeric(14,2) not null default 0,
  vat_amount numeric(14,2) not null default 0,
  gross_amount numeric(14,2) not null default 0,
  recipient_email text,
  status text not null default 'draft'
    check (status in ('draft', 'sent', 'invoiced', 'failed', 'cancelled')),
  sent_at timestamp with time zone,
  invoice_received_at timestamp with time zone,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique (location_id, period_month, billing_direction)
);

drop trigger if exists trg_partner_settlement_reports_updated_at on public.partner_settlement_reports;
create trigger trg_partner_settlement_reports_updated_at
before update on public.partner_settlement_reports
for each row execute function public.set_updated_at();

alter table public.partner_settlement_reports enable row level security;

drop policy if exists "Allow read partner settlement reports" on public.partner_settlement_reports;
create policy "Allow read partner settlement reports"
on public.partner_settlement_reports for select to authenticated using (true);

drop policy if exists "Allow insert partner settlement reports" on public.partner_settlement_reports;
create policy "Allow insert partner settlement reports"
on public.partner_settlement_reports for insert to authenticated with check (true);

drop policy if exists "Allow update partner settlement reports" on public.partner_settlement_reports;
create policy "Allow update partner settlement reports"
on public.partner_settlement_reports for update to authenticated using (true) with check (true);

