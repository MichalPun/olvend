insert into public.location_financial_rules (
  location_id, scope_type, settlement_type, direction, amount, currency,
  unit, periodicity, valid_from, note
)
select
  70, 'location', 'per_unit', 'to_partner', 5, 'CZK',
  'porce', 'monthly', date '2026-08-01',
  'Partner fakturuje OLVENDu 5 Kč včetně 21% DPH za každou vydanou porci.'
where not exists (
  select 1
  from public.location_financial_rules rule
  where rule.location_id = 70
    and rule.direction = 'to_partner'
    and rule.settlement_type = 'per_unit'
    and coalesce(rule.valid_to, date '9999-12-31') >= date '2026-08-01'
);

insert into public.partner_billing_profiles (
  location_id, business_contact_id, device_label, invoice_description_template,
  vat_rate, unit_vat_rate, billing_scope, billing_direction, rate_includes_vat,
  quantity_label, quantity_unit, fixed_monthly_amount, fixed_vat_rate,
  rounding_mode, email_recipient, attachment_mode, billing_data_complete_from,
  billing_data_note, active
)
select
  70,
  contact.id,
  'Luce X2 I · EV 117',
  'Podklad pro fakturaci provozu zařízení {device} - {month}/{year}',
  21,
  21,
  'all_sales',
  'to_partner',
  true,
  'Vydané porce',
  'porcí',
  0,
  21,
  'none',
  'pav.stastny@volny.cz',
  'automatic',
