begin;

create table if not exists public.operator_warehouse_steps (
  id bigint generated by default as identity primary key,
  work_date date not null default current_date,
  employee_id uuid not null references public.employees(id) on delete restrict,
  vehicle_id bigint not null references public.vehicles(id) on delete restrict,
  route_plan_id bigint references public.route_plans(id) on delete set null,
  attendance_day_id bigint references public.attendance_days(id) on delete set null,
  step_key text not null check (step_key in ('load','bagettes','return','waste')),
  item_count integer not null default 0 check (item_count >= 0),
  quantity_total numeric(14,3) not null default 0 check (quantity_total >= 0),
  payload jsonb not null default '{}'::jsonb,
  completed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (work_date, employee_id, vehicle_id, step_key)
);

create index if not exists operator_warehouse_steps_route_idx
  on public.operator_warehouse_steps(route_plan_id, completed_at desc);

alter table public.operator_warehouse_steps enable row level security;

drop policy if exists "Operator reads own warehouse steps" on public.operator_warehouse_steps;
create policy "Operator reads own warehouse steps"
on public.operator_warehouse_steps for select to authenticated
using (employee_id = public.current_employee_id() or public.has_manager_access());

revoke all on public.operator_warehouse_steps from anon;
grant select on public.operator_warehouse_steps to authenticated;

create or replace function public.record_operator_warehouse_step_v66(
  p_step_key text,
  p_vehicle_id bigint,
  p_route_plan_id bigint default null,
  p_attendance_day_id bigint default null,
  p_item_count integer default 0,
  p_quantity_total numeric default 0,
  p_payload jsonb default '{}'::jsonb
)
returns public.operator_warehouse_steps
language plpgsql
security definer
set search_path = public
as $$
declare
  v_employee_id uuid := public.current_employee_id();
  v_row public.operator_warehouse_steps;
begin
  if v_employee_id is null then
    raise exception 'Přihlášený uživatel není propojený se zaměstnancem.';
  end if;
  if p_step_key not in ('load','bagettes','return','waste') then
    raise exception 'Neplatný krok skladu.';
  end if;
  if p_vehicle_id is null or not exists (select 1 from public.vehicles where id = p_vehicle_id and active = true) then
    raise exception 'Vozidlo pro skladový krok není aktivní.';
  end if;
  if coalesce(p_item_count,0) < 0 or coalesce(p_quantity_total,0) < 0 then
    raise exception 'Počet položek ani množství nesmí být záporné.';
  end if;

  insert into public.operator_warehouse_steps (
    work_date, employee_id, vehicle_id, route_plan_id, attendance_day_id,
    step_key, item_count, quantity_total, payload, completed_at
  ) values (
    current_date, v_employee_id, p_vehicle_id, p_route_plan_id, p_attendance_day_id,
    p_step_key, coalesce(p_item_count,0), coalesce(p_quantity_total,0), coalesce(p_payload,'{}'::jsonb), now()
  )
  on conflict (work_date, employee_id, vehicle_id, step_key) do update set
    route_plan_id = excluded.route_plan_id,
    attendance_day_id = excluded.attendance_day_id,
    item_count = excluded.item_count,
    quantity_total = excluded.quantity_total,
    payload = excluded.payload,
    completed_at = excluded.completed_at,
    updated_at = now()
  returning * into v_row;

  return v_row;
end
$$;

revoke all on function public.record_operator_warehouse_step_v66(text,bigint,bigint,bigint,integer,numeric,jsonb) from public;
grant execute on function public.record_operator_warehouse_step_v66(text,bigint,bigint,bigint,integer,numeric,jsonb) to authenticated;

comment on table public.operator_warehouse_steps is
  'Auditní dokončení postupných kroků skladu v OLVEND Operátor, včetně prázdných potvrzených kroků.';

commit;
