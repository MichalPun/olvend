create or replace function public.finance_liability_category_v1(p_description text)
returns text language sql immutable set search_path=public,pg_temp as $$
  select case
    when lower(coalesce(p_description,'')) ~ '(mzdy|mzda|odměn)' then 'Mzdy a lidé'
    when lower(coalesce(p_description,'')) ~ '(sociální|zdravotní|penzijní|pojištění)' then 'Pojištění a odvody'
    when lower(coalesce(p_description,'')) ~ '(daň|dph|finanční úřad|fú)' then 'Daně'
    when lower(coalesce(p_description,'')) ~ '(nájem|energie)' then 'Nájem a provoz'
    when lower(coalesce(p_description,'')) ~ '(splátka|půjčka|úvěr)' then 'Splátky a financování'
    when lower(coalesce(p_description,'')) ~ '(úrok|poplatek|pokuta)' then 'Úroky a poplatky'
    else 'Ostatní závazky' end;
$$;

create or replace function public.finance_import_money_liabilities_v1(
  p_rows jsonb,p_file_name text,p_file_sha256 text,p_exported_at date,p_total_rows integer,p_is_final boolean default false
)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_row jsonb; v_total numeric(18,2); v_actual numeric(18,2); v_orderable numeric(18,2);
  v_status text; v_processed integer:=0; v_count integer; v_remaining numeric(18,2); v_ordered numeric(18,2);
begin
  if not public.finance_can_manage_v1() then raise exception 'Přístup odepřen.' using errcode='42501'; end if;
  if jsonb_typeof(p_rows)<>'array' or jsonb_array_length(p_rows)>100 then raise exception 'Dávka musí obsahovat nejvýše 100 závazků.'; end if;
  if coalesce(p_file_sha256,'') !~ '^[0-9a-f]{64}$' then raise exception 'Neplatný SHA-256 otisk.'; end if;
  for v_row in select value from jsonb_array_elements(p_rows) loop
    v_total:=coalesce((v_row->>'total_amount')::numeric,0);
    v_actual:=coalesce((v_row->>'actual_remaining_amount')::numeric,0);
    v_orderable:=coalesce((v_row->>'orderable_remaining_amount')::numeric,v_actual);
    v_status:=case when abs(v_total)<.01 then 'cancelled' when abs(v_actual)<.01 then 'paid'
      when abs(v_orderable)<abs(v_actual)-.01 then 'ordered'
      when abs(v_actual)<abs(v_total)-.01 then 'partially_paid' else 'unpaid' end;
    insert into public.finance_liabilities(
      source_provider,source_external_id,internal_number,series,series_number,description,category,
      issue_date,accounting_date,taxable_date,due_date,received_date,currency,total_amount,
      actual_remaining_amount,orderable_remaining_amount,ordered_amount,payment_status,accounting_status,
      money_payment_date,money_payment_document,source_file_sha256,source_payload,imported_at,updated_at
    ) values (
      'money_s3',v_row->>'internal_number',v_row->>'internal_number',nullif(v_row->>'series',''),
      nullif(v_row->>'series_number','')::integer,coalesce(nullif(v_row->>'description',''),'Bez popisu'),
      public.finance_liability_category_v1(v_row->>'description'),nullif(v_row->>'issue_date','')::date,
      nullif(v_row->>'accounting_date','')::date,nullif(v_row->>'taxable_date','')::date,
      nullif(v_row->>'due_date','')::date,nullif(v_row->>'received_date','')::date,
      upper(coalesce(nullif(v_row->>'currency',''),'CZK')),v_total,v_actual,v_orderable,
      greatest(v_actual-v_orderable,0),v_status,'not_prepared',nullif(v_row->>'money_payment_date','')::date,
      nullif(v_row->>'money_payment_document',''),p_file_sha256,
      jsonb_build_object('import','Money S3 závazky','source_remaining',v_actual,'source_orderable',v_orderable),now(),now()
    ) on conflict(source_provider,source_external_id) do update set
      internal_number=excluded.internal_number,series=excluded.series,series_number=excluded.series_number,
      description=excluded.description,category=excluded.category,issue_date=excluded.issue_date,
      accounting_date=excluded.accounting_date,taxable_date=excluded.taxable_date,due_date=excluded.due_date,
      received_date=excluded.received_date,currency=excluded.currency,total_amount=excluded.total_amount,
      actual_remaining_amount=excluded.actual_remaining_amount,orderable_remaining_amount=excluded.orderable_remaining_amount,
      ordered_amount=excluded.ordered_amount,payment_status=excluded.payment_status,
      money_payment_date=excluded.money_payment_date,money_payment_document=excluded.money_payment_document,
      source_file_sha256=excluded.source_file_sha256,source_payload=excluded.source_payload,imported_at=now(),updated_at=now();
    v_processed:=v_processed+1;
  end loop;
  if p_is_final then
    select count(*),coalesce(sum(actual_remaining_amount),0),coalesce(sum(ordered_amount),0)
    into v_count,v_remaining,v_ordered from public.finance_liabilities where source_file_sha256=p_file_sha256;
    insert into public.finance_money_liability_imports(source_file_name,source_file_sha256,exported_at,liability_count,
      actual_remaining_amount,ordered_amount,imported_by,updated_at)
    values(p_file_name,p_file_sha256,p_exported_at,coalesce(v_count,p_total_rows),v_remaining,v_ordered,auth.uid(),now())
    on conflict(source_file_sha256) do update set source_file_name=excluded.source_file_name,exported_at=excluded.exported_at,
      liability_count=excluded.liability_count,actual_remaining_amount=excluded.actual_remaining_amount,
      ordered_amount=excluded.ordered_amount,imported_by=excluded.imported_by,updated_at=now();
  end if;
  return jsonb_build_object('processed',v_processed,'final',p_is_final);
end;
$$;

create or replace function public.finance_import_gpc_transactions_v1(
  p_rows jsonb,p_import_sha256 text,p_source_name text,p_statement_count integer,p_total_rows integer,p_is_final boolean default false
)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_row jsonb; v_tx_id bigint; v_invoice_id bigint; v_liability_id bigint; v_amount numeric(18,2);
  v_processed integer:=0; v_invoice_matches integer:=0; v_liability_matches integer:=0;
  v_first date; v_last date; v_total integer;
begin
  if not public.finance_can_manage_v1() then raise exception 'Přístup odepřen.' using errcode='42501'; end if;
  if jsonb_typeof(p_rows)<>'array' or jsonb_array_length(p_rows)>150 then raise exception 'Dávka musí obsahovat nejvýše 150 pohybů.'; end if;
  if coalesce(p_import_sha256,'') !~ '^[0-9a-f]{64}$' then raise exception 'Neplatný SHA-256 otisk.'; end if;
  for v_row in select value from jsonb_array_elements(p_rows) loop
    v_amount:=coalesce((v_row->>'amount')::numeric,0);
    insert into public.finance_bank_transactions(provider,account_id,external_id,booked_on,value_on,amount,currency,
      counterparty_name,counterparty_account,counterparty_bank_code,variable_symbol,message,statement_number,
      booking_code,source_file_name,source_file_sha256,source_sequence,raw_payload)
    values('raiffeisenbank',v_row->>'account_id',v_row->>'external_id',(v_row->>'booked_on')::date,
      nullif(v_row->>'value_on','')::date,v_amount,upper(coalesce(nullif(v_row->>'currency',''),'CZK')),
      nullif(v_row->>'counterparty_name',''),nullif(v_row->>'counterparty_account',''),
      nullif(v_row->>'counterparty_bank_code',''),nullif(v_row->>'variable_symbol',''),nullif(v_row->>'message',''),
      nullif(v_row->>'statement_number',''),nullif(v_row->>'booking_code',''),nullif(v_row->>'source_file_name',''),
      nullif(v_row->>'source_file_sha256',''),nullif(v_row->>'source_sequence','')::integer,v_row)
    on conflict(provider,account_id,external_id) do update set
      booked_on=excluded.booked_on,value_on=excluded.value_on,amount=excluded.amount,currency=excluded.currency,
      counterparty_name=excluded.counterparty_name,counterparty_account=excluded.counterparty_account,
      counterparty_bank_code=excluded.counterparty_bank_code,variable_symbol=excluded.variable_symbol,
      message=excluded.message,raw_payload=excluded.raw_payload,imported_at=now()
    returning id into v_tx_id;
    v_invoice_id:=null; v_liability_id:=null;
    if v_amount<0 and coalesce(v_row->>'variable_symbol','')<>'' then
      select case when count(*)=1 then min(id) end into v_invoice_id
      from public.finance_received_invoices
      where regexp_replace(coalesce(variable_symbol,''),'^0+','')=regexp_replace(v_row->>'variable_symbol','^0+','');
    end if;
    if v_invoice_id is not null then
      insert into public.finance_payment_matches(invoice_id,bank_transaction_id,matched_amount,match_method,confidence,status,confirmed_at)
      values(v_invoice_id,v_tx_id,abs(v_amount),'exact_vs',100,'confirmed',now()) on conflict do nothing;
      v_invoice_matches:=v_invoice_matches+1;
    elsif v_amount<0 then
      select case when count(*)=1 then min(id) end into v_liability_id
      from public.finance_liabilities
      where money_payment_date=(v_row->>'booked_on')::date and abs(total_amount-v_amount*-1)<.01;
      if v_liability_id is not null then
        insert into public.finance_payment_matches(liability_id,bank_transaction_id,matched_amount,match_method,confidence,status,confirmed_at)
        values(v_liability_id,v_tx_id,abs(v_amount),'money_date_amount',99,'confirmed',now()) on conflict do nothing;
        v_liability_matches:=v_liability_matches+1;
      end if;
    end if;
    v_processed:=v_processed+1;
  end loop;

  update public.finance_received_invoices i set
    bank_confirmed_amount=x.amount,bank_last_payment_at=x.last_paid,
    payment_evidence=case when i.payment_evidence='money_s3' then 'mixed' else 'bank' end,
    payment_status=case when x.amount>=abs(i.total_amount)-.01 then 'paid'
      when i.payment_status in ('unpaid','ordered') and x.amount>.01 then 'partially_paid' else i.payment_status end,
    operational_remaining_amount=case when x.amount>=abs(i.total_amount)-.01 then 0
      else i.operational_remaining_amount end,
    status=case when x.amount>=abs(i.total_amount)-.01 then 'settled' else i.status end,updated_at=now()
  from (select m.invoice_id,sum(m.matched_amount) amount,max(t.booked_on) last_paid
    from public.finance_payment_matches m join public.finance_bank_transactions t on t.id=m.bank_transaction_id
    where m.status='confirmed' and m.invoice_id is not null group by m.invoice_id) x where i.id=x.invoice_id;

  update public.finance_liabilities l set
    bank_confirmed_amount=x.amount,bank_last_payment_at=x.last_paid,
    payment_status=case when x.amount>=abs(l.total_amount)-.01 then 'paid'
      when x.amount>.01 then 'partially_paid' else l.payment_status end,updated_at=now()
  from (select m.liability_id,sum(m.matched_amount) amount,max(t.booked_on) last_paid
    from public.finance_payment_matches m join public.finance_bank_transactions t on t.id=m.bank_transaction_id
    where m.status='confirmed' and m.liability_id is not null group by m.liability_id) x where l.id=x.liability_id;

  if p_is_final then
    select count(*),min(booked_on),max(booked_on) into v_total,v_first,v_last
    from public.finance_bank_transactions where raw_payload->>'import_sha256'=p_import_sha256;
    insert into public.finance_bank_imports(import_sha256,source_name,statement_count,transaction_count,first_booked_on,last_booked_on,
      matched_invoice_count,matched_liability_count,imported_by,updated_at)
    values(p_import_sha256,p_source_name,p_statement_count,coalesce(v_total,p_total_rows),v_first,v_last,
      (select count(distinct invoice_id) from public.finance_payment_matches where status='confirmed' and invoice_id is not null),
      (select count(distinct liability_id) from public.finance_payment_matches where status='confirmed' and liability_id is not null),auth.uid(),now())
    on conflict(import_sha256) do update set source_name=excluded.source_name,statement_count=excluded.statement_count,
      transaction_count=excluded.transaction_count,first_booked_on=excluded.first_booked_on,last_booked_on=excluded.last_booked_on,
      matched_invoice_count=excluded.matched_invoice_count,matched_liability_count=excluded.matched_liability_count,
      imported_by=excluded.imported_by,updated_at=now();
  end if;
  return jsonb_build_object('processed',v_processed,'invoice_matches',v_invoice_matches,'liability_matches',v_liability_matches,'final',p_is_final);
end;
$$;

create or replace function public.finance_import_money_received_invoices_v3(
  p_rows jsonb,p_file_name text,p_file_sha256 text,p_exported_at date,p_total_rows integer,p_is_final boolean default false
)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_result jsonb;
begin
  v_result:=public.finance_import_money_received_invoices_v2(
    p_rows,p_file_name,p_file_sha256,p_exported_at,p_total_rows,p_is_final
  );
  update public.finance_received_invoices i set
    accounting_status='not_prepared',handoff_status='not_ready',payment_evidence='money_s3',
    operational_remaining_amount=coalesce(i.money_remaining_amount,case when i.payment_status='paid' then 0 else abs(i.total_amount) end),
    status=case when i.payment_status='cancelled' then 'cancelled' when i.payment_status='paid' then 'settled'
      when i.payment_status='ordered' then 'in_payment_batch' else 'ready_for_payment' end,updated_at=now()
  where i.source_provider='money_s3' and i.source_external_id in (
    select value->>'money_guid' from jsonb_array_elements(p_rows)
  );
  return v_result;
end;
$$;

