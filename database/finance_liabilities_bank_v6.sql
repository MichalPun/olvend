create or replace function public.finance_telemetry_revenue_v1(p_from date,p_to date)
returns numeric language sql stable security definer set search_path=public,pg_temp as $$
  select coalesce(sum(coalesce(e.total_amount_czk,e.quantity*e.unit_price_czk,0)),0)
  from public.telemetry_sales_events e
  where e.source_event_at >= p_from::timestamp at time zone 'Europe/Prague'
    and e.source_event_at < p_to::timestamp at time zone 'Europe/Prague'
    and coalesce(e.price_source,'verified')<>'planogram_estimate'
    and lower(coalesce(e.provider,'')) not like 'test%'
    and not (
      lower(coalesce(e.provider,''))='vendsoft'
      and exists (
        select 1 from public.telemetry_sales_events direct
        where lower(coalesce(direct.provider,''))='ima'
          and direct.machine_id is not distinct from e.machine_id
          and coalesce(direct.selection_code,'')=coalesce(e.selection_code,'')
          and coalesce(direct.product_sku,'')=coalesce(e.product_sku,'')
          and coalesce(direct.quantity,0)=coalesce(e.quantity,0)
          and abs(coalesce(direct.total_amount_czk,0)-coalesce(e.total_amount_czk,0))<=.01
          and direct.source_event_at between e.source_event_at-interval '20 minutes' and e.source_event_at+interval '20 minutes'
      )
    );
$$;

create or replace function public.finance_refresh_telemetry_monthly_v1(p_from date,p_to date)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_month date; v_count integer:=0;
begin
  if not public.finance_can_manage_v1() then raise exception 'Přístup odepřen.' using errcode='42501'; end if;
  v_month:=date_trunc('month',p_from)::date;
  while v_month<date_trunc('month',p_to)::date loop
    insert into public.finance_telemetry_monthly(month_start,revenue,event_count,calculated_at,calculation_method)
    select v_month,public.finance_telemetry_revenue_v1(v_month,(v_month+interval '1 month')::date),
      count(*),now(),'exact_event_dedupe'
    from public.telemetry_sales_events e
    where e.source_event_at>=v_month::timestamp at time zone 'Europe/Prague'
      and e.source_event_at<(v_month+interval '1 month')::timestamp at time zone 'Europe/Prague'
      and coalesce(e.price_source,'verified')<>'planogram_estimate' and lower(coalesce(e.provider,'')) not like 'test%'
    on conflict(month_start) do update set revenue=excluded.revenue,event_count=excluded.event_count,
      calculated_at=excluded.calculated_at,calculation_method=excluded.calculation_method;
    v_count:=v_count+1; v_month:=(v_month+interval '1 month')::date;
  end loop;
  return jsonb_build_object('refreshed_months',v_count);
end;
$$;

create or replace function public.get_finance_dashboard_v2(p_month date)
returns jsonb language sql stable security definer set search_path=public,pg_temp as $$
  with live_month as materialized (
    select date_trunc('month',p_month)::date month_start,
      public.finance_telemetry_revenue_v1(date_trunc('month',p_month)::date,(date_trunc('month',p_month)+interval '1 month')::date) revenue,
      (select count(*) from public.telemetry_sales_events e
        where e.source_event_at>=date_trunc('month',p_month)::timestamp at time zone 'Europe/Prague'
          and e.source_event_at<(date_trunc('month',p_month)+interval '1 month')::timestamp at time zone 'Europe/Prague'
          and coalesce(e.price_source,'verified')<>'planogram_estimate' and lower(coalesce(e.provider,'')) not like 'test%') event_count
    where date_trunc('month',p_month)::date=date_trunc('month',current_date)::date
  ), telemetry_months as materialized (
    select m.month_start::date month_start,
      coalesce(l.revenue,c.revenue,public.finance_telemetry_revenue_v1(m.month_start::date,(m.month_start+interval '1 month')::date)) revenue,
      coalesce(l.event_count,c.event_count,(select count(*) from public.telemetry_sales_events e
        where e.source_event_at>=m.month_start and e.source_event_at<m.month_start+interval '1 month'
          and coalesce(e.price_source,'verified')<>'planogram_estimate' and lower(coalesce(e.provider,'')) not like 'test%')) event_count
    from (select generate_series(date_trunc('month',p_month)-interval '11 months',date_trunc('month',p_month),interval '1 month') month_start) m
    left join live_month l on l.month_start=m.month_start::date
    left join public.finance_telemetry_monthly c on c.month_start=m.month_start::date
  )
  select case when public.finance_can_manage_v1() then jsonb_build_object(
    'revenue_net',coalesce((select revenue from telemetry_months where month_start=date_trunc('month',p_month)::date),0),
    'issued_revenue_net',coalesce((select sum((case when d.document_type='credit_note' then -1 else 1 end)*coalesce(x.net,d.total_amount,0))
      from public.sales_documents d left join lateral (
        select sum(di.quantity*di.unit_price) net from public.sales_document_items di where di.document_id=d.id
      ) x on true
      where d.status in ('issued','paid') and d.document_type<>'advance_invoice' and d.currency='CZK'
        and d.issued_at>=date_trunc('month',p_month) and d.issued_at<date_trunc('month',p_month)+interval '1 month'),0),
    'telemetry_event_count',coalesce((select event_count from telemetry_months where month_start=date_trunc('month',p_month)::date),0),
    'issued_document_count',(select count(*) from public.sales_documents d
      where d.status in ('issued','paid') and d.document_type<>'advance_invoice' and d.currency='CZK'
        and d.issued_at>=date_trunc('month',p_month) and d.issued_at<date_trunc('month',p_month)+interval '1 month'),
    'cash_in_amount',coalesce((select sum(t.amount) from public.finance_bank_transactions t
      where t.amount>0 and t.currency='CZK' and t.booked_on>=date_trunc('month',p_month)::date
        and t.booked_on<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'cash_in_count',(select count(*) from public.finance_bank_transactions t
      where t.amount>0 and t.currency='CZK' and t.booked_on>=date_trunc('month',p_month)::date
        and t.booked_on<(date_trunc('month',p_month)+interval '1 month')::date),
    'cash_out_amount',coalesce((select sum(abs(t.amount)) from public.finance_bank_transactions t
      where t.amount<0 and t.currency='CZK' and t.booked_on>=date_trunc('month',p_month)::date
        and t.booked_on<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'bank_net_flow',coalesce((select sum(t.amount) from public.finance_bank_transactions t
      where t.currency='CZK' and t.booked_on>=date_trunc('month',p_month)::date
        and t.booked_on<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'invoice_cost_net',coalesce((select sum(i.net_amount) from public.finance_received_invoices i
      where i.taxable_date>=date_trunc('month',p_month)::date and i.taxable_date<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'liability_cost',coalesce((select sum(l.total_amount) from public.finance_liabilities l
      where coalesce(l.accounting_date,l.issue_date)>=date_trunc('month',p_month)::date
        and coalesce(l.accounting_date,l.issue_date)<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'operational_costs',coalesce((select sum(i.net_amount) from public.finance_received_invoices i
      where i.taxable_date>=date_trunc('month',p_month)::date and i.taxable_date<(date_trunc('month',p_month)+interval '1 month')::date),0)
      +coalesce((select sum(l.total_amount) from public.finance_liabilities l
      where coalesce(l.accounting_date,l.issue_date)>=date_trunc('month',p_month)::date
        and coalesce(l.accounting_date,l.issue_date)<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'management_result',coalesce((select revenue from telemetry_months where month_start=date_trunc('month',p_month)::date),0)
      -coalesce((select sum(i.net_amount) from public.finance_received_invoices i
      where i.taxable_date>=date_trunc('month',p_month)::date and i.taxable_date<(date_trunc('month',p_month)+interval '1 month')::date),0)
      -coalesce((select sum(l.total_amount) from public.finance_liabilities l
      where coalesce(l.accounting_date,l.issue_date)>=date_trunc('month',p_month)::date
        and coalesce(l.accounting_date,l.issue_date)<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'revenue_ytd',coalesce((select sum(revenue) from telemetry_months where month_start>=date_trunc('year',p_month)::date),0),
    'invoice_cost_ytd',coalesce((select sum(i.net_amount) from public.finance_received_invoices i
      where i.taxable_date>=date_trunc('year',p_month)::date and i.taxable_date<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'liability_cost_ytd',coalesce((select sum(l.total_amount) from public.finance_liabilities l
      where coalesce(l.accounting_date,l.issue_date)>=date_trunc('year',p_month)::date
        and coalesce(l.accounting_date,l.issue_date)<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'performance',(select jsonb_agg(jsonb_build_array(to_char(q.month_start,'YYYY-MM-DD'),q.revenue,q.costs,q.revenue-q.costs) order by q.month_start)
      from (select m.month_start,
        coalesce((select revenue from telemetry_months tm where tm.month_start=m.month_start::date),0) revenue,
        coalesce((select sum(i.net_amount) from public.finance_received_invoices i where i.taxable_date>=m.month_start and i.taxable_date<m.month_start+interval '1 month'),0)
          +coalesce((select sum(l.total_amount) from public.finance_liabilities l where coalesce(l.accounting_date,l.issue_date)>=m.month_start and coalesce(l.accounting_date,l.issue_date)<m.month_start+interval '1 month'),0) costs
        from (select generate_series(date_trunc('month',p_month)-interval '11 months',date_trunc('month',p_month),interval '1 month') month_start) m
      ) q),
    'bank_flow',(select jsonb_agg(jsonb_build_array(to_char(m.month_start,'YYYY-MM-DD'),coalesce((select sum(t.amount) from public.finance_bank_transactions t
      where t.currency='CZK' and t.booked_on>=m.month_start and t.booked_on<m.month_start+interval '1 month'),0)) order by m.month_start)
      from (select generate_series(date_trunc('month',p_month)-interval '6 months',date_trunc('month',p_month),interval '1 month') month_start) m),
    'duplicate_order_warning_count',(select count(distinct bi.invoice_id) from public.finance_payment_batch_items bi
      join public.finance_payment_batches b on b.id=bi.batch_id
      join public.finance_received_invoices i on i.id=bi.invoice_id
      where b.status='awaiting_bank_confirmation' and coalesce(i.bank_confirmed_amount,0)>=abs(i.total_amount)-.01),
    'open_amount',
      coalesce((select sum(greatest(coalesce(operational_remaining_amount,0),0)) from public.finance_received_invoices where payment_status<>'cancelled'),0)
      +coalesce((select sum(greatest(actual_remaining_amount,0)) from public.finance_liabilities where payment_status<>'cancelled'),0),
    'open_count',(select count(*) from public.finance_received_invoices where coalesce(operational_remaining_amount,0)>.01)
      +(select count(*) from public.finance_liabilities where actual_remaining_amount>.01),
    'overdue_amount',coalesce((select sum(operational_remaining_amount) from public.finance_received_invoices where operational_remaining_amount>.01 and due_date<current_date),0)
      +coalesce((select sum(actual_remaining_amount) from public.finance_liabilities where actual_remaining_amount>.01 and due_date<current_date),0),
    'overdue_count',(select count(*) from public.finance_received_invoices where operational_remaining_amount>.01 and due_date<current_date)
      +(select count(*) from public.finance_liabilities where actual_remaining_amount>.01 and due_date<current_date),
    'due_soon_amount',coalesce((select sum(operational_remaining_amount) from public.finance_received_invoices where operational_remaining_amount>.01 and due_date between current_date and current_date+7),0)
      +coalesce((select sum(actual_remaining_amount) from public.finance_liabilities where actual_remaining_amount>.01 and due_date between current_date and current_date+7),0),
    'due_soon_count',(select count(*) from public.finance_received_invoices where operational_remaining_amount>.01 and due_date between current_date and current_date+7)
      +(select count(*) from public.finance_liabilities where actual_remaining_amount>.01 and due_date between current_date and current_date+7),
    'paid_amount',coalesce((select sum(abs(amount)) from public.finance_bank_transactions t where amount<0 and booked_on>=date_trunc('month',p_month)::date and booked_on<(date_trunc('month',p_month)+interval '1 month')::date and exists(select 1 from public.finance_payment_matches m where m.bank_transaction_id=t.id and m.status='confirmed')),0),
    'paid_count',(select count(*) from public.finance_bank_transactions t where amount<0 and booked_on>=date_trunc('month',p_month)::date and booked_on<(date_trunc('month',p_month)+interval '1 month')::date and exists(select 1 from public.finance_payment_matches m where m.bank_transaction_id=t.id and m.status='confirmed')),
    'cost_net',coalesce((select sum(net_amount) from public.finance_received_invoices where taxable_date>=date_trunc('month',p_month)::date and taxable_date<(date_trunc('month',p_month)+interval '1 month')::date),0),
    'new_count',(select count(*) from public.finance_received_invoices where status='new'),
    'approval_count',(select count(*) from public.finance_received_invoices where status='approval'),
    'ready_count',(select count(*) from public.finance_received_invoices where status='ready_for_payment' and payment_status in ('unpaid','partially_paid')),
    'ordered_count',(select count(*) from public.finance_received_invoices where payment_status='ordered')+(select count(*) from public.finance_liabilities where payment_status='ordered'),
    'handoff_count',(select count(*) from public.finance_received_invoices where accounting_status='prepared')+(select count(*) from public.finance_liabilities where accounting_status='prepared'),
    'liability_count',(select count(*) from public.finance_liabilities),
    'liability_open_amount',coalesce((select sum(actual_remaining_amount) from public.finance_liabilities where actual_remaining_amount>.01),0),
    'bank_transaction_count',(select count(*) from public.finance_bank_transactions),
    'bank_last_booked_on',(select max(booked_on) from public.finance_bank_transactions)
  ) else null end;
$$;

