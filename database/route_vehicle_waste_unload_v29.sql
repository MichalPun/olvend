drop policy if exists "Allow insert route vehicle waste" on public.route_vehicle_waste_items;
create policy "Allow insert route vehicle waste"
on public.route_vehicle_waste_items for insert
to anon, authenticated
with check (true);

drop policy if exists "Allow update route vehicle waste" on public.route_vehicle_waste_items;
create policy "Allow update route vehicle waste"
on public.route_vehicle_waste_items for update
to anon, authenticated
using (true)
with check (true);

grant select, insert, update on public.route_vehicle_waste_items to anon, authenticated;
grant usage, select on sequence public.route_vehicle_waste_items_id_seq to anon, authenticated;

create or replace function public.confirm_route_vehicle_waste_unload_v29(
  waste_ids bigint[],
  unloading_employee_id uuid default null
)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
  v_reference text := 'route-waste-unload:' || gen_random_uuid()::text;
  v_requested_count integer;
  v_unloaded_count integer;
begin
  v_requested_count := coalesce(array_length(waste_ids, 1), 0);
  if v_requested_count = 0 then
    raise exception 'K vyložení nebyly předány žádné odpisy.';
  end if;

  if (
    select count(distinct vehicle_id)
    from public.route_vehicle_waste_items
    where id = any(waste_ids)
      and status = 'pending'
  ) <> 1 then
    raise exception 'Vybrané odpisy musí být nevyložené a patřit jednomu vozidlu.';
  end if;

  update public.route_vehicle_waste_items
  set
    status = 'unloaded',
    unloaded_at = now(),
    unloaded_by = unloading_employee_id,
    unload_reference_id = v_reference,
    updated_at = now()
  where id = any(waste_ids)
    and status = 'pending';

  get diagnostics v_unloaded_count = row_count;
  if v_unloaded_count <> v_requested_count then
    raise exception 'Některý odpis už byl vyložen nebo neexistuje (% z %).', v_unloaded_count, v_requested_count;
  end if;

  return jsonb_build_object(
    'unloaded_count', v_unloaded_count,
    'reference_id', v_reference
  );
end
$$;

grant execute on function public.confirm_route_vehicle_waste_unload_v29(bigint[], uuid) to anon, authenticated;

commit;
