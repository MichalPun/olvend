begin;

create table if not exists public.route_vehicle_waste_items (
  id bigint generated by default as identity primary key,
  stock_reference_id text not null unique,
  route_plan_id bigint references public.route_plans (id) on delete set null,
  route_machine_visit_id bigint not null references public.route_machine_visits (id) on delete cascade,
  route_machine_visit_item_id bigint references public.route_machine_visit_items (id) on delete set null,
  machine_id bigint references public.machines (id) on delete set null,
  employee_id uuid references public.employees (id) on delete set null,
  vehicle_id bigint not null references public.vehicles (id) on delete restrict,
  product_id bigint not null references public.products (id) on delete restrict,
  product_sku text,
  product_name text,
  quantity numeric(12,3) not null check (quantity > 0),
  unit text not null default 'ks',
  reason text not null check (reason in ('expired', 'shaken', 'damaged', 'opened', 'other')),
  expiry_date date,
  machine_name text,
  location_name text,
  note text,
  status text not null default 'pending' check (status in ('pending', 'unloaded')),
  collected_at timestamptz not null default now(),
  unloaded_at timestamptz,
  unloaded_by uuid references public.employees (id) on delete set null,
  unload_reference_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists route_vehicle_waste_pending_vehicle_idx
  on public.route_vehicle_waste_items (vehicle_id, status, collected_at);

comment on table public.route_vehicle_waste_items is
  'Fyzické odpisy svezené z automatů. Nejsou použitelnou zásobou vozidla; pending pouze znamená, že sáček ještě nebyl potvrzený ve skladu.';

alter table public.route_vehicle_waste_items enable row level security;

drop policy if exists "Allow read route vehicle waste" on public.route_vehicle_waste_items;
create policy "Allow read route vehicle waste"
on public.route_vehicle_waste_items for select
to anon, authenticated
