-- OLVEND v55: historie kalibrací nápojových automatů.
-- Migrace pouze přidává kalibrační data. Nemění centrální receptury ani skladové odpisy.

begin;

create table if not exists public.machine_calibration_profiles (
  machine_id bigint primary key references public.machines(id) on delete cascade,
  input_time_unit text not null default 'dsec' check (input_time_unit in ('dsec','s')),
  precision_step_dsec numeric(8,3) not null default 1 check (precision_step_dsec > 0),
  layout_columns integer not null default 6 check (layout_columns between 1 and 20),
  rows_per_column integer not null default 4 check (rows_per_column between 1 and 20),
  note text,
  updated_by uuid references public.employees(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.machine_calibrations (
  id bigint generated by default as identity primary key,
  machine_id bigint not null references public.machines(id) on delete restrict,
  technician_employee_id uuid not null references public.employees(id) on delete restrict,
  status text not null default 'draft' check (status in ('draft','completed','cancelled')),
  input_time_unit text not null default 'dsec' check (input_time_unit in ('dsec','s')),
  precision_step_dsec numeric(8,3) not null default 1 check (precision_step_dsec > 0),
  layout_columns integer not null default 6 check (layout_columns between 1 and 20),
  rows_per_column integer not null default 4 check (rows_per_column between 1 and 20),
  recipe_snapshot_version text,
  note text,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists machine_calibrations_one_draft_per_technician_machine
  on public.machine_calibrations(machine_id,technician_employee_id)
  where status='draft';
create index if not exists machine_calibrations_machine_history_idx
  on public.machine_calibrations(machine_id,status,completed_at desc,started_at desc);

create table if not exists public.machine_calibration_measurements (
  id bigint generated by default as identity primary key,
  calibration_id bigint not null references public.machine_calibrations(id) on delete cascade,
  coffee_container_id bigint references public.machine_coffee_containers(id) on delete set null,
  product_id bigint references public.products(id) on delete set null,
  container_code_snapshot text,
  ingredient_name_snapshot text not null,
  calibration_mode text not null default 'timed' check (calibration_mode in ('timed','manual','skip')),
  calibration_time_dsec numeric(12,4),
  measured_amount_g numeric(12,4),
  rate_g_per_dsec numeric(18,8) generated always as (
    case when calibration_mode='timed' and calibration_time_dsec>0 and measured_amount_g>0
      then measured_amount_g/calibration_time_dsec else null end
  ) stored,
  measured_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(calibration_id,coffee_container_id),
  check (
    calibration_mode<>'timed'
    or ((calibration_time_dsec is null or calibration_time_dsec>0)
        and (measured_amount_g is null or measured_amount_g>0))
  )
);

create index if not exists machine_calibration_measurements_calibration_idx
  on public.machine_calibration_measurements(calibration_id,coffee_container_id);

create table if not exists public.machine_calibration_recipe_snapshots (
  id bigint generated by default as identity primary key,
  calibration_id bigint not null references public.machine_calibrations(id) on delete cascade,
  machine_id bigint not null references public.machines(id) on delete restrict,
  coffee_button_id bigint references public.machine_coffee_buttons(id) on delete set null,
  recipe_item_id bigint references public.machine_coffee_recipe_items(id) on delete set null,
  coffee_container_id bigint references public.machine_coffee_containers(id) on delete set null,
  product_id bigint references public.products(id) on delete set null,
  selection_code text not null,
  button_sort_order integer not null default 0,
  grid_column integer,
  grid_row_from_bottom integer,
  beverage_name_snapshot text not null,
  beverage_sku_snapshot text,
  serving_size_snapshot text,
  container_code_snapshot text,
  ingredient_name_snapshot text not null,
  required_quantity numeric(12,4) not null,
  required_unit text not null,
  calibration_mode text not null check (calibration_mode in ('timed','manual','skip')),
  calibration_time_dsec numeric(12,4),
  measured_amount_g numeric(12,4),
  rate_g_per_dsec numeric(18,8),
  calculated_time_raw_dsec numeric(18,8),
  calculated_time_dsec numeric(12,3),
  calculation_status text not null check (calculation_status in (
    'ok','missing_calibration','invalid_calibration','manual','not_applicable','unsupported_unit'
  )),
  recipe_source_updated_at timestamptz,
  created_at timestamptz not null default now(),
  unique(calibration_id,recipe_item_id)
);

create index if not exists machine_calibration_snapshots_calibration_button_idx
  on public.machine_calibration_recipe_snapshots(calibration_id,button_sort_order,selection_code);

create or replace function public.machine_calibration_touch_updated_at()
returns trigger language plpgsql set search_path=pg_catalog,public as $$
begin new.updated_at=now(); return new; end;
$$;

drop trigger if exists trg_machine_calibration_profiles_updated_at on public.machine_calibration_profiles;
create trigger trg_machine_calibration_profiles_updated_at before update on public.machine_calibration_profiles
for each row execute function public.machine_calibration_touch_updated_at();
drop trigger if exists trg_machine_calibrations_updated_at on public.machine_calibrations;
create trigger trg_machine_calibrations_updated_at before update on public.machine_calibrations
for each row execute function public.machine_calibration_touch_updated_at();
drop trigger if exists trg_machine_calibration_measurements_updated_at on public.machine_calibration_measurements;
create trigger trg_machine_calibration_measurements_updated_at before update on public.machine_calibration_measurements
for each row execute function public.machine_calibration_touch_updated_at();

create or replace function public.machine_calibration_current_employee_id()
returns uuid language sql stable security definer set search_path=pg_catalog,public as $$
  select id from public.employees
  where auth_user_id=auth.uid() and active is distinct from false
  order by created_at limit 1
$$;

create or replace function public.machine_calibration_can_manage()
returns boolean language sql stable security definer set search_path=pg_catalog,public as $$
  select exists(
    select 1 from public.employees
    where auth_user_id=auth.uid() and active is distinct from false
      and lower(coalesce(role,'')) in ('admin','manager')
  )
$$;

create or replace function public.machine_calibration_can_write()
returns boolean language sql stable security definer set search_path=pg_catalog,public as $$
  select exists(
    select 1 from public.employees
    where auth_user_id=auth.uid() and active is distinct from false
      and lower(coalesce(role,'')) in ('admin','manager','technician','technik')
  )
$$;

create or replace function public.start_machine_calibration(p_machine_id bigint)
returns bigint language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_employee_id uuid;
  v_calibration_id bigint;
  v_profile public.machine_calibration_profiles%rowtype;
begin
  if not public.machine_calibration_can_write() then raise exception 'Nemáte oprávnění zahájit kalibraci.'; end if;
  v_employee_id:=public.machine_calibration_current_employee_id();
  if v_employee_id is null then raise exception 'Aktivní zaměstnanec nebyl nalezen.'; end if;

  perform 1 from public.machines machine
  where machine.id=p_machine_id and machine.active=true and machine.machine_type ilike 'coffee';
  if not found then raise exception 'Aktivní nápojový automat nebyl nalezen.'; end if;
  if not exists(select 1 from public.machine_coffee_buttons where machine_id=p_machine_id and active)
     or not exists(select 1 from public.machine_coffee_recipe_items where machine_id=p_machine_id and active) then
    raise exception 'Automat nemá aktivní tlačítka nebo receptury.';
  end if;

  select id into v_calibration_id from public.machine_calibrations
  where machine_id=p_machine_id and technician_employee_id=v_employee_id and status='draft'
  order by started_at desc limit 1;
  if v_calibration_id is not null then return v_calibration_id; end if;

  select * into v_profile from public.machine_calibration_profiles where machine_id=p_machine_id;
  insert into public.machine_calibrations(
    machine_id,technician_employee_id,input_time_unit,precision_step_dsec,
    layout_columns,rows_per_column
  ) values(
    p_machine_id,v_employee_id,coalesce(v_profile.input_time_unit,'dsec'),
    coalesce(v_profile.precision_step_dsec,1),coalesce(v_profile.layout_columns,6),
    coalesce(v_profile.rows_per_column,4)
  ) returning id into v_calibration_id;
  return v_calibration_id;
end;
$$;

create or replace function public.save_machine_calibration_draft(
  p_calibration_id bigint,
  p_measurements jsonb,
  p_note text default null
)
returns public.machine_calibrations language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_calibration public.machine_calibrations%rowtype;
  v_employee_id uuid:=public.machine_calibration_current_employee_id();
begin
  if not public.machine_calibration_can_write() then raise exception 'Nemáte oprávnění ukládat kalibraci.'; end if;
  select * into strict v_calibration from public.machine_calibrations where id=p_calibration_id for update;
  if v_calibration.status<>'draft' then raise exception 'Upravit lze pouze rozpracovanou kalibraci.'; end if;
  if v_calibration.technician_employee_id<>v_employee_id and not public.machine_calibration_can_manage() then
    raise exception 'Tuto kalibraci může upravit pouze její technik.';
  end if;
  if jsonb_typeof(coalesce(p_measurements,'[]'::jsonb))<>'array' then raise exception 'Měření musí být pole.'; end if;

  if exists(
    select 1 from jsonb_array_elements(coalesce(p_measurements,'[]'::jsonb)) item
    left join public.machine_coffee_containers container
      on container.id=nullif(item->>'coffee_container_id','')::bigint
     and container.machine_id=v_calibration.machine_id and container.active
    where container.id is null
      or coalesce(item->>'calibration_mode','timed') not in ('timed','manual','skip')
      or (coalesce(item->>'calibration_mode','timed')='timed' and (
        (nullif(replace(item->>'calibration_time_dsec',',','.'),'') is not null
          and nullif(replace(item->>'calibration_time_dsec',',','.'),'')::numeric<=0)
        or (nullif(replace(item->>'measured_amount_g',',','.'),'') is not null
          and nullif(replace(item->>'measured_amount_g',',','.'),'')::numeric<=0)
      ))
  ) then raise exception 'Některé měření je neplatné nebo nepatří tomuto automatu.'; end if;

  delete from public.machine_calibration_measurements where calibration_id=p_calibration_id;
  insert into public.machine_calibration_measurements(
    calibration_id,coffee_container_id,product_id,container_code_snapshot,
    ingredient_name_snapshot,calibration_mode,calibration_time_dsec,measured_amount_g,measured_at
  )
  select p_calibration_id,container.id,container.product_id,container.container_code,
    container.product_name,coalesce(item->>'calibration_mode','timed'),
    case when coalesce(item->>'calibration_mode','timed')='timed'
      then nullif(replace(item->>'calibration_time_dsec',',','.'),'')::numeric else null end,
    case when coalesce(item->>'calibration_mode','timed')='timed'
      then nullif(replace(item->>'measured_amount_g',',','.'),'')::numeric else null end,
    coalesce(nullif(item->>'measured_at','')::timestamptz,now())
  from jsonb_array_elements(coalesce(p_measurements,'[]'::jsonb)) item
  join public.machine_coffee_containers container
    on container.id=nullif(item->>'coffee_container_id','')::bigint
   and container.machine_id=v_calibration.machine_id and container.active;

  update public.machine_calibrations set note=nullif(btrim(p_note),'') where id=p_calibration_id
  returning * into v_calibration;
  return v_calibration;
end;
$$;

create or replace function public.complete_machine_calibration(
  p_calibration_id bigint,
  p_measurements jsonb,
  p_note text default null
)
returns public.machine_calibrations language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_calibration public.machine_calibrations%rowtype;
  v_employee_id uuid:=public.machine_calibration_current_employee_id();
begin
  perform public.save_machine_calibration_draft(p_calibration_id,p_measurements,p_note);
  select * into strict v_calibration from public.machine_calibrations where id=p_calibration_id for update;
  if v_calibration.technician_employee_id<>v_employee_id and not public.machine_calibration_can_manage() then
    raise exception 'Tuto kalibraci může dokončit pouze její technik.';
  end if;
  if exists(
    select 1
    from public.machine_coffee_recipe_items recipe
    join public.machine_coffee_buttons button
      on button.id=recipe.coffee_button_id and button.machine_id=recipe.machine_id and button.active
    left join public.machine_calibration_measurements measurement
      on measurement.calibration_id=v_calibration.id
     and measurement.coffee_container_id=recipe.coffee_container_id
    where recipe.machine_id=v_calibration.machine_id and recipe.active and lower(recipe.unit)='g'
      and (measurement.id is null or (
        measurement.calibration_mode='timed' and (
          measurement.calibration_time_dsec is null or measurement.calibration_time_dsec<=0
          or measurement.measured_amount_g is null or measurement.measured_amount_g<=0
        )
      ))
  ) then
    raise exception 'Kalibraci nelze dokončit: některá časovaná surovina nemá platný čas a naváženou hmotnost.';
  end if;

  delete from public.machine_calibration_recipe_snapshots where calibration_id=p_calibration_id;
  insert into public.machine_calibration_recipe_snapshots(
    calibration_id,machine_id,coffee_button_id,recipe_item_id,coffee_container_id,product_id,
    selection_code,button_sort_order,grid_column,grid_row_from_bottom,
    beverage_name_snapshot,beverage_sku_snapshot,serving_size_snapshot,
    container_code_snapshot,ingredient_name_snapshot,required_quantity,required_unit,
    calibration_mode,calibration_time_dsec,measured_amount_g,rate_g_per_dsec,
    calculated_time_raw_dsec,calculated_time_dsec,calculation_status,recipe_source_updated_at
  )
  select v_calibration.id,v_calibration.machine_id,button.id,recipe.id,container.id,
    coalesce(recipe.product_id,container.product_id),button.selection_code,button.sort_order,
    button.grid_column,button.grid_row_from_bottom,button.product_name,button.product_sku,
    substring(button.product_name from '([0-9]{2,4}[[:space:]]*ml)'),
    coalesce(recipe.container_code,container.container_code),
    coalesce(recipe.ingredient_name,container.product_name,'Surovina'),
    recipe.quantity_per_vend,recipe.unit,
    coalesce(measurement.calibration_mode,case when lower(recipe.unit)='ks' then 'skip' else 'timed' end),
    measurement.calibration_time_dsec,measurement.measured_amount_g,measurement.rate_g_per_dsec,
    case when lower(recipe.unit)='g' and measurement.calibration_mode='timed'
                   and measurement.calibration_time_dsec>0 and measurement.measured_amount_g>0
      then recipe.quantity_per_vend*measurement.calibration_time_dsec/measurement.measured_amount_g end,
    case when lower(recipe.unit)='g' and measurement.calibration_mode='timed'
                   and measurement.calibration_time_dsec>0 and measurement.measured_amount_g>0
      then round((recipe.quantity_per_vend*measurement.calibration_time_dsec/measurement.measured_amount_g)
                 /v_calibration.precision_step_dsec)*v_calibration.precision_step_dsec end,
    case
      when lower(recipe.unit)='ks' then 'not_applicable'
      when lower(recipe.unit)<>'g' then 'unsupported_unit'
      when measurement.calibration_mode='manual' then 'manual'
      when measurement.calibration_mode='skip' then 'not_applicable'
      when measurement.id is null then 'missing_calibration'
      when measurement.calibration_time_dsec<=0 or measurement.measured_amount_g<=0 then 'invalid_calibration'
      else 'ok'
    end,
    recipe.updated_at
  from public.machine_coffee_buttons button
  join public.machine_coffee_recipe_items recipe
    on recipe.machine_id=button.machine_id and recipe.coffee_button_id=button.id and recipe.active
  left join public.machine_coffee_containers container
    on container.id=recipe.coffee_container_id and container.active
  left join public.machine_calibration_measurements measurement
    on measurement.calibration_id=v_calibration.id and measurement.coffee_container_id=recipe.coffee_container_id
  where button.machine_id=v_calibration.machine_id and button.active;

  update public.machine_calibrations
  set status='completed',completed_at=now(),cancelled_at=null,
      recipe_snapshot_version=format('machine:%s completed:%s items:%s',machine_id,now(),
        (select count(*) from public.machine_calibration_recipe_snapshots where calibration_id=p_calibration_id))
  where id=p_calibration_id returning * into v_calibration;
  return v_calibration;
end;
$$;

create or replace function public.cancel_machine_calibration(p_calibration_id bigint,p_note text default null)
returns public.machine_calibrations language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_calibration public.machine_calibrations%rowtype;
  v_employee_id uuid:=public.machine_calibration_current_employee_id();
begin
  if not public.machine_calibration_can_write() then raise exception 'Nemáte oprávnění rušit kalibraci.'; end if;
  select * into strict v_calibration from public.machine_calibrations where id=p_calibration_id for update;
  if v_calibration.status<>'draft' then raise exception 'Zrušit lze pouze rozpracovanou kalibraci.'; end if;
  if v_calibration.technician_employee_id<>v_employee_id and not public.machine_calibration_can_manage() then
    raise exception 'Tuto kalibraci může zrušit pouze její technik.';
  end if;
  update public.machine_calibrations set status='cancelled',cancelled_at=now(),note=coalesce(nullif(btrim(p_note),''),note)
  where id=p_calibration_id returning * into v_calibration;
  return v_calibration;
end;
$$;

create or replace function public.save_machine_calibration_profile(
  p_machine_id bigint,p_input_time_unit text,p_precision_step_dsec numeric,
  p_layout_columns integer,p_rows_per_column integer,p_note text default null
)
returns public.machine_calibration_profiles language plpgsql security definer set search_path=pg_catalog,public as $$
declare v_profile public.machine_calibration_profiles%rowtype;
begin
  if not public.machine_calibration_can_manage() then raise exception 'Nastavení kalibrací může měnit pouze administrátor.'; end if;
  if p_input_time_unit not in ('dsec','s') or p_precision_step_dsec<=0
     or p_layout_columns not between 1 and 20 or p_rows_per_column not between 1 and 20 then
    raise exception 'Neplatné nastavení kalibrace.';
  end if;
  insert into public.machine_calibration_profiles(
    machine_id,input_time_unit,precision_step_dsec,layout_columns,rows_per_column,note,updated_by
  ) values(p_machine_id,p_input_time_unit,p_precision_step_dsec,p_layout_columns,p_rows_per_column,
           nullif(btrim(p_note),''),public.machine_calibration_current_employee_id())
  on conflict(machine_id) do update set input_time_unit=excluded.input_time_unit,
    precision_step_dsec=excluded.precision_step_dsec,layout_columns=excluded.layout_columns,
    rows_per_column=excluded.rows_per_column,note=excluded.note,updated_by=excluded.updated_by,updated_at=now()
  returning * into v_profile;
  return v_profile;
end;
$$;

