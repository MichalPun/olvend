create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

create table if not exists public.accounting_report_settings (
  id smallint primary key default 1 check (id = 1),
  enabled boolean not null default true,
  recipient_email text,
  cc_email text,
  send_day smallint not null default 2 check (send_day between 1 and 28),
  send_hour smallint not null default 7 check (send_hour between 0 and 23),
  timezone text not null default 'Europe/Prague',
  updated_at timestamp with time zone not null default now()
);

insert into public.accounting_report_settings (id, enabled)
values (1, true)
on conflict (id) do update set
  enabled = true,
  updated_at = now();

create table if not exists public.accounting_report_runs (
  id bigint generated by default as identity primary key,
  period_month date not null unique check (date_trunc('month', period_month)::date = period_month),
  recipient_email text not null,
  cc_email text,
  status text not null check (status in ('processing', 'sent', 'failed')),
  provider_id text,
  row_count integer,
  total_revenue_czk numeric(14,2),
  error_message text,
  started_at timestamp with time zone not null default now(),
  sent_at timestamp with time zone,
  created_at timestamp with time zone not null default now()
);

alter table public.accounting_report_settings enable row level security;
alter table public.accounting_report_runs enable row level security;

drop policy if exists "Allow managers to read accounting report settings" on public.accounting_report_settings;
create policy "Allow managers to read accounting report settings"
on public.accounting_report_settings for select to authenticated
using (public.has_payroll_access());

drop policy if exists "Allow managers to update accounting report settings" on public.accounting_report_settings;
create policy "Allow managers to update accounting report settings"
on public.accounting_report_settings for update to authenticated
using (public.has_payroll_access()) with check (public.has_payroll_access());

drop policy if exists "Allow managers to read accounting report runs" on public.accounting_report_runs;
create policy "Allow managers to read accounting report runs"
on public.accounting_report_runs for select to authenticated
using (public.has_payroll_access());

