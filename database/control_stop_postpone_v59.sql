begin;

-- Odlozeni kontrolni zastavky vytvari novou kontrolni trasu. Bezne doplnovaci
-- route_plans ani route_plan_stops tato migrace zamerne nemeni.
alter table public.control_route_stops
  add column if not exists postponed_to_control_route_id bigint references public.control_routes(id) on delete set null,
  add column if not exists postponed_from_stop_id bigint references public.control_route_stops(id) on delete set null;

create table if not exists public.control_visit_handoffs (
  id bigint generated by default as identity primary key,
  control_route_id bigint not null references public.control_routes(id) on delete cascade,
  control_route_stop_id bigint not null references public.control_route_stops(id) on delete cascade,
  location_id bigint not null references public.locations(id) on delete cascade,
  machine_id bigint null references public.machines(id) on delete cascade,
  location_operator_message_id bigint not null references public.location_operator_messages(id) on delete cascade,
  title text not null,
  message text not null,
  created_by uuid not null references public.employees(id) on delete restrict,
  created_at timestamptz not null default now()
);

create index if not exists control_visit_handoffs_route_idx
  on public.control_visit_handoffs(control_route_id,control_route_stop_id,created_at);

alter table public.control_visit_handoffs enable row level security;
drop policy if exists control_visit_handoffs_access on public.control_visit_handoffs;
create policy control_visit_handoffs_access on public.control_visit_handoffs
for select to authenticated using (
  exists (
    select 1 from public.control_routes r
    where r.id=control_route_id
      and (r.assigned_employee_id=public.current_employee_id() or public.has_manager_access())
  )
);

create or replace function public.postpone_control_stop_v59(
  p_control_route_stop_id bigint,
  p_planned_date date,
  p_planned_start_time time,
  p_reason text,
  p_note text default null
) returns jsonb
language plpgsql
security definer
set search_path=pg_catalog,public
as $$
declare
  v_employee uuid:=public.current_employee_id();
  v_source record;
  v_new_route_id bigint;
  v_new_stop_id bigint;
  v_machine_count integer;
  v_reason text:=nullif(trim(p_reason),'');
  v_note text:=nullif(trim(coalesce(p_note,'')),'');
begin
  if v_employee is null then raise exception 'Přihlášení vypršelo.' using errcode='42501'; end if;
  if p_planned_date<current_date then raise exception 'Návštěvu nelze odložit do minulosti.'; end if;
  if v_reason is null then raise exception 'Vyberte důvod odložení.'; end if;

  select s.*,r.name route_name,r.control_type,r.planned_date source_date,r.assigned_employee_id,
         r.instructions route_instructions,r.checklist_config route_checklist,r.rule_config route_rules,r.status route_status
    into v_source
  from public.control_route_stops s
  join public.control_routes r on r.id=s.control_route_id
  where s.id=p_control_route_stop_id
  for update of s;

  if not found or (v_source.assigned_employee_id<>v_employee and not public.has_manager_access()) then
    raise exception 'Kontrolní zastávka není dostupná.' using errcode='42501';
  end if;
  if v_source.route_status<>'in_progress' or v_source.status in ('completed','skipped') then
    raise exception 'Odložit lze jen nedokončenou zastávku v probíhající kontrolní trase.';
  end if;

  select count(*) into v_machine_count
  from public.control_route_machines
  where control_route_stop_id=v_source.id and status not in ('completed','skipped');
  if v_machine_count=0 then raise exception 'Na zastávce už nezbývá žádný nedokončený automat.'; end if;

  insert into public.control_routes(
    name,control_type,planned_date,planned_start_time,assigned_employee_id,status,instructions,
    checklist_config,rule_config,published_at,created_by
  ) values (
    'Odložená kontrola · '||v_source.location_name_snapshot,'follow_up',p_planned_date,p_planned_start_time,
    v_source.assigned_employee_id,'published',
    concat_ws(E'\n',v_source.route_instructions,'Navazuje na trasu #'||v_source.control_route_id||'. Důvod: '||v_reason,
      case when v_note is not null then 'Poznámka: '||v_note end),
    v_source.route_checklist,v_source.route_rules,now(),v_employee
  ) returning id into v_new_route_id;

  insert into public.control_route_stops(
    control_route_id,location_id,stop_order,status,location_name_snapshot,address_snapshot,city_snapshot,
    latitude_snapshot,longitude_snapshot,instruction,postponed_from_stop_id
  ) values (
    v_new_route_id,v_source.location_id,1,'planned',v_source.location_name_snapshot,v_source.address_snapshot,
    v_source.city_snapshot,v_source.latitude_snapshot,v_source.longitude_snapshot,
    concat_ws(E'\n',v_source.instruction,'Odloženo z kontroly #'||v_source.control_route_id||': '||v_reason,
      case when v_note is not null then v_note end),v_source.id
  ) returning id into v_new_stop_id;

  insert into public.control_route_machines(
    control_route_stop_id,machine_id,machine_kind,status,evidence_number_snapshot,machine_name_snapshot,
    checklist_config,snapshot
  )
  select v_new_stop_id,machine_id,machine_kind,'planned',evidence_number_snapshot,machine_name_snapshot,
         checklist_config,snapshot||jsonb_build_object('postponed_from_control_route_machine_id',id)
  from public.control_route_machines
  where control_route_stop_id=v_source.id and status not in ('completed','skipped');

  update public.control_route_machines
  set status='skipped',updated_at=now()
  where control_route_stop_id=v_source.id and status not in ('completed','skipped');

  update public.control_route_stops
  set status='skipped',skipped_at=now(),skip_reason=concat_ws(' · ',v_reason,v_note),
      postponed_to_control_route_id=v_new_route_id,updated_at=now()
  where id=v_source.id;

  return jsonb_build_object(
    'ok',true,'source_stop_id',v_source.id,'new_control_route_id',v_new_route_id,'new_control_route_stop_id',v_new_stop_id,
    'planned_date',p_planned_date,'planned_start_time',p_planned_start_time,'machine_count',v_machine_count
  );
end;
$$;

create or replace function public.save_control_visit_handoff_v59(
  p_control_route_stop_id bigint,
  p_machine_id bigint,
  p_title text,
  p_message text
) returns jsonb
language plpgsql
security definer
set search_path=pg_catalog,public
as $$
declare
  v_employee uuid:=public.current_employee_id();
  v_context record;
  v_message_id bigint;
  v_handoff_id bigint;
  v_title text:=coalesce(nullif(trim(p_title),''),'Na co si dát pozor při příští návštěvě');
  v_message text:=nullif(trim(p_message),'');
begin
  if v_employee is null then raise exception 'Přihlášení vypršelo.' using errcode='42501'; end if;
  if v_message is null then raise exception 'Napište konkrétní pokyn pro příští návštěvu.'; end if;
  select s.control_route_id,s.location_id,r.assigned_employee_id,r.status
    into v_context
  from public.control_route_stops s join public.control_routes r on r.id=s.control_route_id
  where s.id=p_control_route_stop_id;
  if not found or (v_context.assigned_employee_id<>v_employee and not public.has_manager_access()) then
    raise exception 'Kontrolní zastávka není dostupná.' using errcode='42501';
  end if;
  if v_context.status not in ('in_progress','completed') then raise exception 'Pokyn lze uložit až po zahájení kontroly.'; end if;
  if p_machine_id is not null and not exists(
    select 1 from public.machines m where m.id=p_machine_id and m.location_id=v_context.location_id
  ) then raise exception 'Vybraný automat nepatří na tuto lokalitu.'; end if;

  insert into public.location_operator_messages(
    location_id,machine_id,title,message,display_mode,requires_acknowledgement,is_active,created_by_employee_id
  ) values (
    v_context.location_id,p_machine_id,v_title,v_message,'next_visit',true,true,v_employee
  ) returning id into v_message_id;

  insert into public.control_visit_handoffs(
    control_route_id,control_route_stop_id,location_id,machine_id,location_operator_message_id,title,message,created_by
  ) values (
    v_context.control_route_id,p_control_route_stop_id,v_context.location_id,p_machine_id,v_message_id,v_title,v_message,v_employee
  ) returning id into v_handoff_id;

  return jsonb_build_object('ok',true,'handoff_id',v_handoff_id,'operator_message_id',v_message_id);
end;
$$;

create or replace function public.get_control_route_protocol_v59(p_route_id bigint)
returns jsonb language plpgsql stable security definer set search_path=pg_catalog,public as $$
declare v_protocol jsonb;
begin
  v_protocol:=public.get_control_route_protocol_v58(p_route_id);
  return v_protocol||jsonb_build_object(
    'handoffs',coalesce((
      select jsonb_agg(jsonb_build_object(
        'stop_id',h.control_route_stop_id,'machine_id',h.machine_id,'title',h.title,'message',h.message,
        'operator_message_id',h.location_operator_message_id,'created_at',h.created_at,
        'created_by',trim(concat_ws(' ',e.name,e.surname))
      ) order by h.created_at)
      from public.control_visit_handoffs h left join public.employees e on e.id=h.created_by
      where h.control_route_id=p_route_id
    ),'[]'::jsonb)
  );
end;
$$;

revoke all on function public.postpone_control_stop_v59(bigint,date,time,text,text) from public,anon;
revoke all on function public.save_control_visit_handoff_v59(bigint,bigint,text,text) from public,anon;
revoke all on function public.get_control_route_protocol_v59(bigint) from public,anon;
grant execute on function public.postpone_control_stop_v59(bigint,date,time,text,text) to authenticated;
grant execute on function public.save_control_visit_handoff_v59(bigint,bigint,text,text) to authenticated;
grant execute on function public.get_control_route_protocol_v59(bigint) to authenticated;

comment on function public.postpone_control_stop_v59(bigint,date,time,text,text) is
  'Uzavře původní kontrolní zastávku jako odloženou a nedokončené automaty atomicky převede do nové publikované kontrolní trasy.';
comment on table public.control_visit_handoffs is
  'Provozní pokyny vzniklé při kontrole, které se propisují do protokolu i do příští běžné návštěvy lokality.';

notify pgrst,'reload schema';
commit;
