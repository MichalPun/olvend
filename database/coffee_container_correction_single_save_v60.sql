begin;

create table if not exists public.machine_coffee_container_correction_audit (
  id bigint generated by default as identity primary key,
  correction_key text not null unique,
  coffee_container_id bigint not null references public.machine_coffee_containers(id) on delete restrict,
  machine_id bigint not null references public.machines(id) on delete restrict,
  before_quantity numeric(12,3),
  after_quantity numeric(12,3) not null,
  capacity_quantity numeric(12,3),
  unit text not null,
  reason text not null,
  source text not null,
  context jsonb not null default '{}'::jsonb,
  created_by uuid null references public.employees(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists machine_coffee_container_correction_audit_container_idx
  on public.machine_coffee_container_correction_audit(coffee_container_id,created_at desc);

alter table public.machine_coffee_container_correction_audit enable row level security;
drop policy if exists machine_coffee_container_correction_audit_manager_read
  on public.machine_coffee_container_correction_audit;
create policy machine_coffee_container_correction_audit_manager_read
  on public.machine_coffee_container_correction_audit
  for select to authenticated
  using (public.has_manager_access());

do $$
declare
  v_container public.machine_coffee_containers%rowtype;
  v_target record;
  v_key text;
begin
  for v_target in
    select * from (values
      (530::bigint,83::bigint,'Z3'::text,'oVe COFFEE CREAMER WHITE 1 kg'::text,'BVK Hády · fyzicky hlášeno plné 20. 10. 2026'::text),
      (680::bigint,128::bigint,'Z1'::text,'Barbera Tris 1 kg'::text,'Domov seniorů Břeclav Jetinno · fyzicky hlášeno plné 20. 10. 2026'::text),
      (685::bigint,128::bigint,'Z6'::text,'AG PRO Matcha Latte Malina 1 kg'::text,'Domov seniorů Břeclav Jetinno · fyzicky hlášeno plné 20. 10. 2026'::text)
    ) as target(container_id,machine_id,container_code,product_name,reason)
  loop
    select * into v_container
    from public.machine_coffee_containers
    where id=v_target.container_id
    for update;

    if not found
       or v_container.machine_id<>v_target.machine_id
       or v_container.container_code<>v_target.container_code
       or v_container.product_name<>v_target.product_name
       or v_container.active is not true then
      raise exception 'Zásobník % neodpovídá očekávanému stroji, pozici nebo produktu.',v_target.container_id;
    end if;
    if v_container.capacity_quantity is null or v_container.capacity_quantity<=0 then
      raise exception 'Zásobník % nemá platnou kapacitu.',v_target.container_id;
    end if;

    v_key:='manager-physical-report-20261020-'||v_target.container_id;
    if not exists(select 1 from public.machine_coffee_container_correction_audit where correction_key=v_key) then
      insert into public.machine_coffee_container_correction_audit(
        correction_key,coffee_container_id,machine_id,before_quantity,after_quantity,capacity_quantity,unit,reason,source,context
      ) values (
        v_key,v_container.id,v_container.machine_id,v_container.current_quantity,v_container.capacity_quantity,
        v_container.capacity_quantity,v_container.unit,v_target.reason,'manager_physical_report',
        jsonb_build_object('reported_fill_percent',100,'reported_date','2026-10-20','repair_version',60)
      );

      update public.machine_coffee_containers
      set current_quantity=capacity_quantity,
          physical_counted_at=now(),
          physical_count_source='manager_physical_report',
          physical_count_visit_item_id=null,
          updated_at=now()
      where id=v_container.id;
    end if;
  end loop;
end $$;

comment on table public.machine_coffee_container_correction_audit is
  'Audit cílených fyzických korekcí zásobníků, které zakládají novou telemetrickou výchozí hodnotu.';

notify pgrst,'reload schema';
commit;
