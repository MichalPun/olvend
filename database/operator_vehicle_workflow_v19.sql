comment on column public.operational_requests.attachment_urls is
  'Veřejné URL fotografií závady nebo souvisejících dokumentů.';

create table if not exists public.vehicle_daily_checks (
  id bigint generated by default as identity primary key,
  vehicle_id bigint not null references public.vehicles(id) on delete cascade,
  employee_id uuid not null references public.employees(id) on delete cascade,
  attendance_day_id bigint references public.attendance_days(id) on delete set null,
  check_date date not null default current_date,
  body_ok boolean not null default false,
  tires_ok boolean not null default false,
  lights_ok boolean not null default false,
  equipment_ok boolean not null default false,
  fluids_ok boolean not null default false,
  load_secured_ok boolean not null default false,
  note text,
  checked_at timestamp with time zone,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique(vehicle_id, employee_id, check_date)
);

create index if not exists vehicle_daily_checks_vehicle_date_idx
  on public.vehicle_daily_checks(vehicle_id, check_date desc);

create index if not exists vehicle_daily_checks_employee_date_idx
  on public.vehicle_daily_checks(employee_id, check_date desc);

drop trigger if exists trg_vehicle_daily_checks_updated_at on public.vehicle_daily_checks;
create trigger trg_vehicle_daily_checks_updated_at
before update on public.vehicle_daily_checks
for each row execute function public.set_vehicle_operation_logs_updated_at();

alter table public.vehicle_daily_checks enable row level security;

drop policy if exists "Authenticated read vehicle daily checks" on public.vehicle_daily_checks;
create policy "Authenticated read vehicle daily checks"
on public.vehicle_daily_checks for select
to authenticated
using (true);

drop policy if exists "Employee insert own vehicle daily check" on public.vehicle_daily_checks;
create policy "Employee insert own vehicle daily check"
on public.vehicle_daily_checks for insert
to authenticated
with check (employee_id = public.current_employee_id());

drop policy if exists "Employee update own vehicle daily check" on public.vehicle_daily_checks;
create policy "Employee update own vehicle daily check"
on public.vehicle_daily_checks for update
to authenticated
using (employee_id = public.current_employee_id())
with check (employee_id = public.current_employee_id());

grant select, insert, update on public.vehicle_daily_checks to authenticated;
grant usage, select on sequence public.vehicle_daily_checks_id_seq to authenticated;

grant select, insert, update on public.operational_requests to authenticated;
