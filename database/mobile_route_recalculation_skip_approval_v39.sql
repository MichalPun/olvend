create or replace function public.guard_route_stop_skip_approval_v39()
returns trigger language plpgsql set search_path = public as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' and current_user not in ('postgres','supabase_admin') then
    if exists(select 1 from public.route_stop_skip_requests r where r.route_plan_id = new.route_plan_id and r.status = 'pending') then
      raise exception 'Trasa čeká na schválení nejeté zastávky.';
    end if;
    if new.status = 'skipped' and old.status is distinct from 'skipped'
       and not exists(select 1 from public.route_stop_skip_requests r where r.route_plan_stop_id = new.id and r.status = 'approved') then
      raise exception 'Nejetou zastávku musí nejdřív schválit vedoucí.';
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists trg_guard_route_stop_skip_approval_v39 on public.route_plan_stops;
create trigger trg_guard_route_stop_skip_approval_v39 before update on public.route_plan_stops
for each row execute function public.guard_route_stop_skip_approval_v39();

create or replace function public.guard_route_plan_pending_skip_v39()
returns trigger language plpgsql set search_path = public as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' and current_user not in ('postgres','supabase_admin')
     and exists(select 1 from public.route_stop_skip_requests r where r.route_plan_id = new.id and r.status = 'pending')
     and (new.execution_status is distinct from old.execution_status or new.completed_at is distinct from old.completed_at) then
    raise exception 'Trasu nelze uzavřít, dokud čeká žádost o nejetí.';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_guard_route_plan_pending_skip_v39 on public.route_plans;
create trigger trg_guard_route_plan_pending_skip_v39 before update on public.route_plans
for each row execute function public.guard_route_plan_pending_skip_v39();

