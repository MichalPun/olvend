create table if not exists public.route_stop_skip_requests (
  id uuid primary key default gen_random_uuid(),
  route_plan_id bigint not null references public.route_plans(id) on delete cascade,
  route_plan_stop_id bigint not null references public.route_plan_stops(id) on delete cascade,
  operator_employee_id uuid not null references public.employees(id) on delete restrict,
  approver_employee_id uuid not null references public.employees(id) on delete restrict,
  reason text not null check (reason in ('opening_hours','time_shortage','location_closed','no_access','machine_unavailable','other')),
  note text,
  status text not null default 'pending' check (status in ('pending','approved','rejected','cancelled')),
  approval_token_hash text not null,
  requested_at timestamptz not null default now(),
  email_sent_at timestamptz,
  email_delivery_id text,
  mail_error text,
  decided_at timestamptz,
  decision_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists route_stop_skip_requests_one_pending_plan_idx
  on public.route_stop_skip_requests(route_plan_id)
  where status = 'pending';
create index if not exists route_stop_skip_requests_operator_idx
  on public.route_stop_skip_requests(operator_employee_id, requested_at desc);
create unique index if not exists route_stop_skip_requests_token_idx
  on public.route_stop_skip_requests(approval_token_hash);

create table if not exists public.route_mobile_recalculations (
  id bigint generated by default as identity primary key,
  route_plan_id bigint not null references public.route_plans(id) on delete cascade,
  employee_id uuid references public.employees(id) on delete set null,
  trigger_key text not null,
  previous_stop_ids bigint[] not null,
  ordered_stop_ids bigint[] not null,
  provider text not null default 'google_routes',
  baseline_distance_meters integer,
  distance_meters integer,
  baseline_duration_seconds integer,
  duration_seconds integer,
  reason text,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(route_plan_id, trigger_key)
);

alter table public.route_skip_approvers enable row level security;
alter table public.route_stop_skip_requests enable row level security;
alter table public.route_mobile_recalculations enable row level security;
revoke all on public.route_skip_approvers from anon, authenticated;
revoke all on public.route_stop_skip_requests from anon, authenticated;
