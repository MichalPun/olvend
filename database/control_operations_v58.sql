create or replace function public.get_control_machine_workflow_v58(p_control_route_machine_id bigint)
returns jsonb language plpgsql stable security definer set search_path=pg_catalog,public as $$
declare v_employee uuid:=public.current_employee_id(); v_result jsonb;
begin
  if v_employee is null then raise exception 'Přihlášení vypršelo.' using errcode='42501'; end if;
  if not exists(
    select 1 from public.control_route_machines crm
    join public.control_route_stops crs on crs.id=crm.control_route_stop_id
    join public.control_routes cr on cr.id=crs.control_route_id
    where crm.id=p_control_route_machine_id
      and (cr.assigned_employee_id=v_employee or public.has_manager_access())
  ) then raise exception 'Kontrolní automat není dostupný.' using errcode='42501'; end if;

  select jsonb_build_object(
    'pending_price_changes',coalesce((
      select jsonb_agg(jsonb_build_object(
        'id',i.id,'batch_id',i.batch_id,'target_type',i.target_type,
        'target_id',coalesce(i.planogram_slot_id,i.coffee_button_id),
        'slot_code',i.slot_code,'product_name',i.product_name,
        'old_price_czk',i.old_price_czk,'new_price_czk',i.new_price_czk,
        'label_printed_at',i.label_printed_at,'status',i.status
      ) order by i.slot_code)
      from public.control_route_machines crm
      join public.machine_price_change_items i on i.machine_id=crm.machine_id and i.status='pending'
      where crm.id=p_control_route_machine_id
    ),'[]'::jsonb),
    'label_request',(
      select jsonb_build_object(
        'id',r.id,'request_code',r.request_code,'status',r.status,'issue_types',r.issue_types,'note',r.note,
        'assigned_employee_id',r.assigned_employee_id,'assigned_employee',(
          select trim(concat_ws(' ',e.name,e.surname)) from public.employees e where e.id=r.assigned_employee_id
        ),'task_id',r.task_id,'technical_job_id',r.technical_job_id,
        'created_at',r.created_at,'printed_at',r.printed_at,
        'items',coalesce((select jsonb_agg(to_jsonb(ri) order by ri.slot_code) from public.machine_price_label_request_items ri where ri.request_id=r.id),'[]'::jsonb)
      )
      from public.machine_price_label_requests r
      where r.control_route_machine_id=p_control_route_machine_id and r.status in ('requested','printed')
      order by r.created_at desc limit 1
    ),
    'departure_photos',coalesce((
      select jsonb_agg(jsonb_build_object('id',p.id,'storage_path',p.storage_path,'created_at',p.created_at) order by p.created_at desc)
      from public.control_machine_photos p where p.control_route_machine_id=p_control_route_machine_id and p.photo_type='departure'
    ),'[]'::jsonb)
  ) into v_result;
  return coalesce(v_result,jsonb_build_object('pending_price_changes','[]'::jsonb,'label_request',null));
end;
$$;

create or replace function public.save_control_price_label_request_v58(
  p_control_route_machine_id bigint,
  p_items jsonb,
  p_issue_types jsonb default '[]'::jsonb,
  p_assigned_employee_id uuid default null,
  p_note text default null
) returns jsonb language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_employee uuid:=public.current_employee_id(); v_context record; v_request public.machine_price_label_requests%rowtype;
  v_item jsonb; v_slot public.machine_planogram_slots%rowtype; v_button public.machine_coffee_buttons%rowtype;
  v_message text; v_count integer:=0; v_assignee public.employees%rowtype; v_ev text;
begin
  if v_employee is null then raise exception 'Přihlášení vypršelo.' using errcode='42501'; end if;
  if jsonb_typeof(coalesce(p_items,'[]'::jsonb))<>'array' or jsonb_typeof(coalesce(p_issue_types,'[]'::jsonb))<>'array' then
    raise exception 'Neplatné položky kontroly cenovek.';
  end if;
  if jsonb_array_length(coalesce(p_items,'[]'::jsonb))=0 and jsonb_array_length(coalesce(p_issue_types,'[]'::jsonb))=0 then
    raise exception 'Vyberte cenovky nebo provozní závadu.';
  end if;
  if p_assigned_employee_id is null then raise exception 'Vyberte, komu má být náprava předána.'; end if;
  select * into v_assignee from public.employees where id=p_assigned_employee_id and active is distinct from false;
  if not found then raise exception 'Vybraný pracovník není aktivní.'; end if;
  if exists(select 1 from jsonb_array_elements_text(coalesce(p_issue_types,'[]'::jsonb)) x(value) where lower(x.value) like '%lišt%')
     and lower(coalesce(v_assignee.role,'')) !~ '(technik|technician|servis)' then
    raise exception 'Chybějící nebo poškozenou cenovkovou lištu je nutné předat technikovi.';
  end if;
  select crm.*,crs.control_route_id,crs.location_id,cr.status route_status,cr.assigned_employee_id
  into v_context
  from public.control_route_machines crm
  join public.control_route_stops crs on crs.id=crm.control_route_stop_id
  join public.control_routes cr on cr.id=crs.control_route_id
  where crm.id=p_control_route_machine_id;
  if not found or (v_context.assigned_employee_id<>v_employee and not public.has_manager_access()) then
    raise exception 'Kontrolní automat není dostupný.' using errcode='42501';
  end if;
  if v_context.route_status='cancelled' then raise exception 'Zrušenou kontrolní trasu nelze měnit.'; end if;

  select * into v_request from public.machine_price_label_requests
  where control_route_machine_id=p_control_route_machine_id and status in ('requested','printed')
  order by created_at desc limit 1 for update;
  if not found then
    insert into public.machine_price_label_requests(
      request_code,control_route_id,control_route_stop_id,control_route_machine_id,machine_id,note,created_by_employee_id
    ) values(
      'CEN-'||to_char(clock_timestamp(),'YYYYMMDD-HH24MISS')||'-'||upper(substr(gen_random_uuid()::text,1,4)),
      v_context.control_route_id,v_context.control_route_stop_id,p_control_route_machine_id,v_context.machine_id,
      nullif(trim(coalesce(p_note,'')),''),v_employee
    ) returning * into v_request;
  else
    update public.machine_price_label_requests set status='requested',printed_at=null,completed_at=null,issue_types=coalesce(p_issue_types,'[]'::jsonb),assigned_employee_id=p_assigned_employee_id,note=nullif(trim(coalesce(p_note,'')),'') where id=v_request.id returning * into v_request;
    delete from public.machine_price_label_request_items where request_id=v_request.id;
  end if;
  update public.machine_price_label_requests set issue_types=coalesce(p_issue_types,'[]'::jsonb),assigned_employee_id=p_assigned_employee_id where id=v_request.id returning * into v_request;

  for v_item in select * from jsonb_array_elements(p_items) loop
    if v_item->>'target_type'='food_slot' then
      select * into v_slot from public.machine_planogram_slots
      where id=(v_item->>'target_id')::bigint and machine_id=v_context.machine_id and active is true;
      if not found then raise exception 'Pozice cenovky nebyla nalezena.'; end if;
      insert into public.machine_price_label_request_items(request_id,target_type,target_record_id,slot_code,product_sku,product_name,price_czk)
      values(v_request.id,'food_slot',v_slot.id,v_slot.slot_code,v_slot.product_sku,coalesce(v_slot.product_name,'Bez produktu'),coalesce(v_slot.pending_price_czk,v_slot.planned_price_czk,v_slot.customer_price_czk,v_slot.price_czk,v_slot.dex_price_czk));
    elsif v_item->>'target_type'='coffee_button' then
      select * into v_button from public.machine_coffee_buttons
      where id=(v_item->>'target_id')::bigint and machine_id=v_context.machine_id and active is true;
      if not found then raise exception 'Volba nápoje nebyla nalezena.'; end if;
      insert into public.machine_price_label_request_items(request_id,target_type,target_record_id,slot_code,product_sku,product_name,price_czk)
      values(v_request.id,'coffee_button',v_button.id,v_button.selection_code,v_button.product_sku,coalesce(v_button.product_name,'Bez produktu'),coalesce(v_button.planned_price_czk,v_button.customer_price_czk,v_button.sale_price_czk));
    else raise exception 'Neplatný typ cenovky.'; end if;
    v_count:=v_count+1;
  end loop;

  v_message:=format('Náprava cenovek %s: %s pozic (%s). Závady: %s. Po vytištění vezměte cenovky a potřebné lišty na další návštěvu.',v_request.request_code,v_count,coalesce((
    select string_agg(ri.slot_code,', ' order by ri.slot_code) from public.machine_price_label_request_items ri where ri.request_id=v_request.id
  ),'bez dotisku'),coalesce((select string_agg(value,', ') from jsonb_array_elements_text(coalesce(p_issue_types,'[]'::jsonb))), 'jen dotisk'));
  select coalesce(evidence_number::text,id::text) into v_ev from public.machines where id=v_context.machine_id;
  if lower(coalesce(v_assignee.role,'')) ~ '(technik|technician|servis)' then
    if v_request.technical_job_id is null then
      insert into public.technical_jobs(job_type,status,priority,title,description,location_id,machine_id,assigned_employee_id,configuration_kind,configuration_payload,planned_date,due_at,qr_token,created_by)
      values('service','assigned','high','EV '||v_ev||' · cenovky nebo cenovková lišta',v_message,v_context.location_id,v_context.machine_id,p_assigned_employee_id,'general',jsonb_build_object('source','control_route','label_request_id',v_request.id),current_date+7,(current_date+7)::timestamptz,gen_random_uuid()::text,v_employee)
      returning id into v_request.technical_job_id;
    else
      update public.technical_jobs set status='assigned',priority='high',description=v_message,assigned_employee_id=p_assigned_employee_id,planned_date=current_date+7,due_at=(current_date+7)::timestamptz where id=v_request.technical_job_id;
    end if;
    if v_request.task_id is not null then update public.tasks set status='done',note=concat_ws(E'\n',note,'Převedeno na servisní zásah.') where id=v_request.task_id; end if;
  else
    if v_request.task_id is null then
      insert into public.tasks(title,note,status,priority,due_date,assigned_employee_id,created_by)
      values('EV '||v_ev||' · náprava cenovek',v_message,'new','important',current_date+7,p_assigned_employee_id,v_employee)
      returning id into v_request.task_id;
    else
      update public.tasks set status='new',priority='important',note=v_message,due_date=current_date+7,assigned_employee_id=p_assigned_employee_id where id=v_request.task_id;
    end if;
    if v_request.technical_job_id is not null then update public.technical_jobs set status='cancelled',note=concat_ws(E'\n',note,'Převedeno na úkol provozu.') where id=v_request.technical_job_id; end if;
  end if;
  update public.machine_price_label_requests set assigned_employee_id=p_assigned_employee_id,task_id=v_request.task_id,technical_job_id=v_request.technical_job_id where id=v_request.id;
  return jsonb_build_object('ok',true,'request_id',v_request.id,'request_code',v_request.request_code,'item_count',v_count,
    'assigned_employee',trim(concat_ws(' ',v_assignee.name,v_assignee.surname)),'technical_job_id',v_request.technical_job_id,'task_id',v_request.task_id,
    'print_url','price-label-print.html?machine='||v_context.machine_id::text||'&label_request='||v_request.id::text);
end;
$$;

