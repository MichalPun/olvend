create or replace function public.get_control_revenue_trend_v58(p_machine_ids bigint[],p_months integer default 6)
returns table(machine_id bigint,month_start date,revenue_czk numeric)
language sql stable security definer set search_path=pg_catalog,public as $$
  with limits as (
    select greatest(2,least(coalesce(p_months,6),12)) n,date_trunc('month',timezone('Europe/Prague',now()))::date current_month
  ), requested as (
    select m.id,m.sales_tracking_mode from public.machines m where m.id=any(coalesce(p_machine_ids,array[]::bigint[]))
  ), months as (
    select generate_series((l.current_month-(l.n-1)*interval '1 month')::date,l.current_month,interval '1 month')::date month_start from limits l
  ), telemetry_ranked as (
    select e.*,(e.source_event_at at time zone 'Europe/Prague')::date sale_date,
      bool_or(lower(coalesce(e.provider,''))='ima') over(partition by e.machine_id,(e.source_event_at at time zone 'Europe/Prague')::date) has_ima
    from public.telemetry_sales_events e,limits l
    where e.machine_id=any(coalesce(p_machine_ids,array[]::bigint[])) and e.source_event_at>=((l.current_month-(l.n-1)*interval '1 month')::timestamp at time zone 'Europe/Prague')
  ), telemetry_monthly as (
    select e.machine_id,date_trunc('month',e.sale_date)::date month_start,sum(coalesce(e.total_amount_czk,0)) revenue
    from telemetry_ranked e where not(lower(coalesce(e.provider,''))='vendsoft' and e.has_ima) group by e.machine_id,date_trunc('month',e.sale_date)::date
  ), manual_monthly as (
    select r.machine_id,date_trunc('month',r.reading_at at time zone 'Europe/Prague')::date month_start,sum(greatest(coalesce(r.revenue_delta_czk,0),0)) revenue
    from public.machine_manual_counter_readings r,limits l
    where r.machine_id=any(coalesce(p_machine_ids,array[]::bigint[])) and r.reading_at>=((l.current_month-(l.n-1)*interval '1 month')::timestamp at time zone 'Europe/Prague')
    group by r.machine_id,date_trunc('month',r.reading_at at time zone 'Europe/Prague')::date
  )
  select q.id,m.month_start,round(case when q.sales_tracking_mode='manual_counters' then coalesce(mm.revenue,0) else coalesce(tm.revenue,0) end,2)
  from requested q cross join months m left join telemetry_monthly tm on tm.machine_id=q.id and tm.month_start=m.month_start
  left join manual_monthly mm on mm.machine_id=q.id and mm.month_start=m.month_start
  where public.security_active_employee() order by q.id,m.month_start;
$$;

create or replace function public.apply_control_price_change_v58(p_control_route_machine_id bigint,p_price_change_item_id uuid)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_employee uuid:=public.current_employee_id(); v_context record; v_item public.machine_price_change_items%rowtype; v_pending integer; v_adjustment_id bigint;
begin
  if v_employee is null then raise exception 'Přihlášení vypršelo.' using errcode='42501'; end if;
  select crm.*,crs.control_route_id,cr.status route_status,cr.assigned_employee_id into v_context
  from public.control_route_machines crm join public.control_route_stops crs on crs.id=crm.control_route_stop_id join public.control_routes cr on cr.id=crs.control_route_id
  where crm.id=p_control_route_machine_id;
  if not found or (v_context.assigned_employee_id<>v_employee and not public.has_manager_access()) then raise exception 'Kontrolní automat není dostupný.' using errcode='42501'; end if;
  if v_context.route_status not in ('in_progress','completed') then raise exception 'Nejdřív zahajte kontrolní trasu.'; end if;
  select * into v_item from public.machine_price_change_items where id=p_price_change_item_id and machine_id=v_context.machine_id for update;
  if not found then raise exception 'Připravená změna ceny nebyla nalezena.'; end if;
  if v_item.status='applied' then return jsonb_build_object('ok',true,'already_applied',true); end if;
  if v_item.status<>'pending' then raise exception 'Tuto změnu už nelze provést.'; end if;
  if v_item.target_type='food_slot' then
    update public.machine_planogram_slots set price_czk=v_item.new_price_czk,customer_price_czk=v_item.new_price_czk,dex_price_czk=v_item.new_price_czk,pending_price_czk=null
    where id=v_item.planogram_slot_id and machine_id=v_context.machine_id;
  else
    update public.machine_coffee_buttons set sale_price_czk=v_item.new_price_czk,customer_price_czk=v_item.new_price_czk
    where id=v_item.coffee_button_id and machine_id=v_context.machine_id;
    update public.machine_planogram_slots set price_czk=v_item.new_price_czk,customer_price_czk=v_item.new_price_czk,dex_price_czk=v_item.new_price_czk,pending_price_czk=null
    where machine_id=v_context.machine_id and slot_code=v_item.slot_code;
  end if;
  update public.machine_price_change_items set status='applied',applied_by_employee_id=v_employee,applied_at=now() where id=v_item.id;
