-- Provozní návaznost kontrolní trasy: výběr chybějících cenovek,
-- předání nápravy konkrétnímu pracovníkovi a potvrzení již připravených změn cen.
create table if not exists public.machine_price_label_requests (
  id uuid primary key default gen_random_uuid(),
  request_code text not null unique,
  control_route_id bigint references public.control_routes(id) on delete set null,
  control_route_stop_id bigint references public.control_route_stops(id) on delete set null,
  control_route_machine_id bigint references public.control_route_machines(id) on delete set null,
  machine_id bigint not null references public.machines(id) on delete cascade,
  status text not null default 'requested' check (status in ('requested','printed','completed','cancelled')),
  issue_types jsonb not null default '[]'::jsonb,
  note text,
  assigned_employee_id uuid references public.employees(id) on delete set null,
  task_id bigint references public.tasks(id) on delete set null,
  technical_job_id bigint references public.technical_jobs(id) on delete set null,
  location_operator_message_id bigint references public.location_operator_messages(id) on delete set null,
  created_by_employee_id uuid references public.employees(id) on delete set null,
  printed_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.control_findings
  add column if not exists task_id bigint references public.tasks(id) on delete set null,
  add column if not exists technical_job_id bigint references public.technical_jobs(id) on delete set null;

create table if not exists public.control_machine_photos (
  id bigint generated by default as identity primary key,
  control_route_id bigint not null references public.control_routes(id) on delete cascade,
  control_route_stop_id bigint not null references public.control_route_stops(id) on delete cascade,
  control_route_machine_id bigint not null references public.control_route_machines(id) on delete cascade,
  machine_id bigint not null references public.machines(id) on delete cascade,
  photo_type text not null default 'departure' check (photo_type in ('arrival','departure','detail')),
  storage_path text not null,
  file_name text,
  mime_type text,
  created_by uuid references public.employees(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.machine_price_label_request_items (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.machine_price_label_requests(id) on delete cascade,
  target_type text not null check (target_type in ('food_slot','coffee_button')),
  target_record_id bigint not null,
  slot_code text not null,
  product_sku text,
  product_name text not null,
  price_czk numeric(10,2),
  printed_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  unique(request_id, target_type, target_record_id)
);

create index if not exists machine_price_label_requests_machine_idx
  on public.machine_price_label_requests(machine_id, status, created_at desc);

alter table public.machine_price_label_requests enable row level security;
alter table public.machine_price_label_request_items enable row level security;
alter table public.control_machine_photos enable row level security;
revoke all on public.machine_price_label_requests, public.machine_price_label_request_items from anon, authenticated;
