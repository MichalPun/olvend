create or replace function public.save_control_finding_v58(
  p_control_route_machine_id bigint,p_control_route_stop_id bigint,p_control_check_result_id bigint,
  p_category text,p_severity text,p_description text,p_resolution_type text,p_assigned_employee_id uuid,
  p_due_date date,p_operation_decision text,p_context_snapshot jsonb default '{}'::jsonb
) returns jsonb language plpgsql security definer set search_path=pg_catalog,public as $$
declare
  v_employee uuid:=public.current_employee_id(); v_context record; v_assignee public.employees%rowtype;
  v_finding_id bigint; v_task_id bigint; v_job_id bigint; v_title text; v_priority text;
begin
  if v_employee is null then raise exception 'Přihlášení vypršelo.' using errcode='42501'; end if;
  if nullif(trim(coalesce(p_description,'')),'') is null then raise exception 'Popište, co bylo zjištěno.'; end if;
  if p_severity not in ('low','medium','high','critical') or p_resolution_type not in ('fixed_now','task') or p_operation_decision not in ('continue','limited','stop') then raise exception 'Neplatné zadání nálezu.'; end if;
  select s.control_route_id,s.location_id,s.location_name_snapshot,r.status route_status,r.assigned_employee_id,cm.machine_id,cm.evidence_number_snapshot
  into v_context from public.control_route_stops s join public.control_routes r on r.id=s.control_route_id
  left join public.control_route_machines cm on cm.id=p_control_route_machine_id and cm.control_route_stop_id=s.id
  where s.id=p_control_route_stop_id;
  if not found or (v_context.assigned_employee_id<>v_employee and not public.has_manager_access()) then raise exception 'Kontrolní místo není dostupné.' using errcode='42501'; end if;
  if v_context.route_status not in ('in_progress','completed') then raise exception 'Kontrolní trasa není zahájena.'; end if;
  if p_control_route_machine_id is not null and v_context.machine_id is null then raise exception 'Automat nepatří do kontrolovaného místa.'; end if;
  if p_control_check_result_id is not null and not exists(select 1 from public.control_check_results c where c.id=p_control_check_result_id and c.control_route_stop_id=p_control_route_stop_id) then raise exception 'Kontrolní bod nebyl nalezen.'; end if;
  if p_resolution_type='task' then
    if p_assigned_employee_id is null then raise exception 'Vyberte, komu nápravný úkol předáváte.'; end if;
    select * into v_assignee from public.employees where id=p_assigned_employee_id and active is distinct from false;
    if not found then raise exception 'Vybraný pracovník není aktivní.'; end if;
    if p_category='Technická závada' and lower(coalesce(v_assignee.role,'')) !~ '(technik|technician|servis)' then raise exception 'Technickou závadu je nutné předat technikovi.'; end if;
  end if;
  insert into public.control_findings(control_route_id,control_route_stop_id,control_route_machine_id,control_check_result_id,category,severity,description,resolution_type,assigned_employee_id,due_date,operation_decision,status,resolved_at,resolved_by,context_snapshot,created_by)
  values(v_context.control_route_id,p_control_route_stop_id,p_control_route_machine_id,p_control_check_result_id,p_category,p_severity,trim(p_description),p_resolution_type,p_assigned_employee_id,
    case when p_resolution_type='task' then p_due_date else null end,p_operation_decision,case when p_resolution_type='fixed_now' then 'resolved' else 'open' end,
    case when p_resolution_type='fixed_now' then now() else null end,case when p_resolution_type='fixed_now' then v_employee else null end,coalesce(p_context_snapshot,'{}'::jsonb),v_employee)
  returning id into v_finding_id;
  if p_resolution_type='task' then
    v_title:=case when v_context.evidence_number_snapshot is not null then 'EV '||v_context.evidence_number_snapshot::text else v_context.location_name_snapshot end||' · '||p_category;
    if lower(coalesce(v_assignee.role,'')) ~ '(technik|technician|servis)' then
      v_priority:=case p_severity when 'critical' then 'critical' when 'high' then 'high' else 'normal' end;
      insert into public.technical_jobs(job_type,status,priority,title,description,location_id,machine_id,assigned_employee_id,configuration_kind,configuration_payload,planned_date,due_at,qr_token,created_by)
      values('service','assigned',v_priority,v_title,trim(p_description),v_context.location_id,v_context.machine_id,p_assigned_employee_id,'general',jsonb_build_object('source','control_finding','finding_id',v_finding_id),coalesce(p_due_date,current_date+7),coalesce(p_due_date,current_date+7)::timestamptz,gen_random_uuid()::text,v_employee)
      returning id into v_job_id;
    else
      v_priority:=case when p_severity in ('critical','high') then 'today' when p_severity='medium' then 'important' else 'normal' end;
      insert into public.tasks(title,note,status,priority,due_date,assigned_employee_id,created_by)
      values(v_title,trim(p_description),'new',v_priority,coalesce(p_due_date,current_date+7),p_assigned_employee_id,v_employee)
      returning id into v_task_id;
    end if;
    update public.control_findings set task_id=v_task_id,technical_job_id=v_job_id where id=v_finding_id;
  end if;
  return jsonb_build_object('ok',true,'finding_id',v_finding_id,'task_id',v_task_id,'technical_job_id',v_job_id);
end;
$$;

